    # C2 floors
    for nid in ("C2-floor-025", "C2-floor-05", "C2-floor-1"):
        r = res[nid]
        c = r["data"].get("c")
        if c is None:
            continue
        tag = mname("CtwoFloor", nid.split("-")[-1])
        m = re.search(r"no loss vs no floor \([^)]*\): (\d+/\d+)", r["verdict"])
        N.add(tag + "NoLoss", m.group(1) if m else "--")
        m = re.search(r"TOST\(10%\) non-inferior: (\d+/\d+)", r["verdict"])
        N.add(tag + "TostNonInferior", m.group(1) if m else "--")
        m = re.search(r"probe decays at >= floor rate: (\d+/\d+)", r["verdict"])
        N.add(tag + "ProbeAboveFloor", m.group(1) if m else "--")
