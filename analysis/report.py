def _ev(r, n=None):
    ev = r.get("evidence") or []
    return "\n".join(f"    {e}" if e.startswith("  ") else f"  - {e}" for e in (ev if n is None else ev[:n]))


def c2_meaning(res, store) -> str:
    out = []
    pole = {}
    for s_, ss in store.runs("C1-where").items():
        v = [((r.get("memory_probe") or {}).get("lora") or {}) for r in ss.values()]
        v = [p["alpha_sfm"] / p["alpha_design"] for p in v if "alpha_sfm" in p]
        if v:
            pole[s_] = float(np.median(v))
    if pole:
        out.append("Without a floor the learned SFM's slowest pole sits at " + ", ".join(
            f"{s_} {x:.2f}" for s_, x in pole.items()) + " x alpha (HyperKKL, median over seeds); the SFM's initial "
            "slowest pole is alpha/1.5^5 = 0.13 alpha, so values near 0.13 mean the memory is inherited from the "
            "initialisation rather than learned (Reviewer-B).")
    f5 = res["C2-floor-05"]
    v = re.search(r"no loss vs no floor \([^)]*\): (\d+)/(\d+)", f5["verdict"])
    if v:
        k, n = int(v.group(1)), int(v.group(2))
        lost = [s_ for s_, d in f5["data"]["pairs"].items() if any(R.worse(x["p"]) for x in d.values())]
        out.append(f"Forcing it to forget at 0.5 alpha costs nothing significant on {k}/{n} dev systems (rule needs 5/6)"
                   + (f"; significant losses on {', '.join(lost)}" if lost else "") + ".")
    W = res["C2-window-a1"]["data"].get("W") or {}
    if W:
        l = {s_: d["l_dec_q95"] for s_, d in W.items()}
        top = max(l, key=l.get)
        out.append("Decoder Lipschitz proxy l_dec_q95 per system: " + ", ".join(f"{s_} {x:.0f}" for s_, x in l.items())
                   + f" (largest: {top}). The plain window L* = ln(1/eta)/alpha ignores l; the refined "
                   "(ln(1/eta) + ln l)/alpha is longer exactly where l is large (post hoc, not pre-registered).")
    return " ".join(out)


def c3_meaning(res, store, scen) -> str:
    from .figures import c3_grid
    G = c3_grid(store, DEV, "sequence_ood", scen)
    out = []
    for lab, nid, cond, k, m in scen:                     # exact-model scenarios
        if m == 0 and k == "full":
            bs = [b for (l, _), b in G.items() if l == lab and b]
            if bs:
                w = sum(R.better(b["comps"]["any"]["p"]) for b in bs if "any" in b["comps"])
                lo = sum(R.worse(b["comps"]["any"]["p"]) for b in bs if "any" in b["comps"])
                out.append(f"Exact model ({lab}): HyperKKL beats the best filter on {w}/{len(bs)}, loses on {lo}/{len(bs)}.")
    lf = sorted({f"{l} ({s_})" for (l, s_), b in G.items() if b and R.failed(b["means"][b["BL"]], b["clim"])})
    if lf:
        out.append("HyperKKL is itself above climatology (FAILED) in: " + ", ".join(lf) +
                   ". Learned observers trained on the nominal sensor/plant are not robust to gross outliers or to "
                   "post-training plant drift.")
    pts = []
    for (l, s_), b in G.items():
        k_, m_ = next((k, m) for lab, _, _, k, m in scen if lab == l)
        if not b or (k_ == "full" and m_ == 0) or l.startswith("drift"):
            continue
        c = b["comps"].get("working")
        win = R.better(c["p"]) if c else not R.failed(b["means"][b["BL"]], b["clim"])
        pts.append((rel_model_error(s_, k_, m_), win, f"{l}/{s_}"))
    if pts:
        wins = [p for p in pts if p[1]]
        loss = [p for p in pts if not p[1]]
        txt = f"Model-wrong cells (mismatch, partial, realistic): HyperKKL beats the best WORKING filter in {len(wins)}/{len(pts)}"
        if wins and loss:
            txt += (f"; smallest model error with a win {min(wins)[0]:.3f} ({min(wins)[2]}), largest without a win "
                    f"{max(loss)[0]:.3f} ({max(loss)[2]}); non-wins: " + ", ".join(p[2] for p in sorted(loss)))
        out.append(txt + ".")
    infl = []
    for (l, s_), b in G.items():
        if b and b["BF"] in b["failed"] and "working" in b["comps"] and "any" in b["comps"]:
            infl.append(f"{l}/{s_}: {100 * b['comps']['any']['p']['rel']:+.0f}% vs FAILED {b['BF']} but "
                        f"{100 * b['comps']['working']['p']['rel']:+.0f}% vs working {b['comps']['working']['filter']}")
    if infl:
        out.append(f"In {len(infl)} cells the overall best filter is itself FAILED; quote the working-filter change, e.g. "
                   + "; ".join(infl[:4]) + ".")
    return " ".join(out)


