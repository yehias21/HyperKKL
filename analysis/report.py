def _n2w(n: int) -> str:
    if n < 20:
        return _W[n]
    if n < 100:
        return _T[n // 10] + (_W[n % 10] if n % 10 else "")
    return "".join(_W[int(d)] for d in str(n))


def mname(*parts) -> str:
    s = ""
    for p in parts:
        for tok in re.split(r"[^A-Za-z0-9]+", str(p)):
            if not tok:
                continue
            tok = re.sub(r"\d+", lambda m: _n2w(int(m.group())), tok)
            s += tok[0].upper() + tok[1:]
    return s


TS = {"id": "Id", "shape_ood": "Shape", "sequence_ood": "Seq"}


class Numbers:
    def __init__(self):
        self.d = {}

    def add(self, name, value, note=""):
        name = mname(name) if not re.fullmatch(r"[A-Za-z]+", name) else name
        self.d[name] = (str(value), note)

    def write(self, path: Path):
        L = ["% generated by analysis/paper_results.py -- every number quoted in the text. Do not edit.",
             f"% generated {_dt.datetime.now():%Y-%m-%d %H:%M}", ""]
        for k, (v, note) in sorted(self.d.items()):
            v = v.replace("%", r"\%")
            L.append(f"\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{v}}}" + (f"  % {note}" if note else ""))
        path.write_text("\n".join(L) + "\n")


def pc(x, d=0):
    return "--" if x is None or not np.isfinite(x) else f"{100 * x:+.{d}f}%"


