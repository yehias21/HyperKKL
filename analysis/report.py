            hv = c["hyper_vs_lora"]
            N.add(f"{pre}DenseAblationBeatsHyperKKL{TS[tier]}", f"{len(hv['hyper_better'])}/{hv['n']}")
            N.add(f"{pre}HyperKKLBeatsDenseAblation{TS[tier]}", f"{len(hv['lora_better'])}/{hv['n']}")
