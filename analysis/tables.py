def esc(s) -> str:
    s = str(s)
    rep = [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"),
           ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
           (">=", r"$\geq$"), ("<=", r"$\leq$"), ("->", r"$\rightarrow$"), ("+-", r"$\pm$"),
           ("||", r"$\|$"), ("µ", r"$\mu$"), ("α", r"$\alpha$"), ("−", "-"), ("…", "...")]
    for a, b in rep:
        s = s.replace(a, b)
    s = re.sub(r"(?<!\$)<(?!\$)", r"$<$", s)
    s = re.sub(r"(?<!\$)>(?!\$)", r"$>$", s)
    return s


