def compile_pdfs(tex_files: list, out: Path, numbers: Path = None) -> dict:
    """Compile each table in a 6.5in-text-width wrapper. Returns {name: 'ok' | error}."""
    status = {}
    if not shutil.which("pdflatex"):
        return {p.stem: "pdflatex not found" for p in tex_files}
    build = out / "build"
    build.mkdir(parents=True, exist_ok=True)
    pre = r"\input{%s}" % numbers.resolve() if numbers else ""
    for p in tex_files:
        w = build / f"{p.stem}_preview.tex"
        w.write_text(WRAP % (pre, r"\input{%s}" % p.resolve()))
        ok = True
        for _ in range(2):            # longtable needs two passes
            r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", w.name], cwd=build,
                               capture_output=True, text=True, timeout=120)
            ok = r.returncode == 0
            if not ok:
                break
        log = (build / f"{p.stem}_preview.log").read_text(errors="replace") if (build / f"{p.stem}_preview.log").exists() else ""
        over = re.findall(r"Overfull \\hbox \((\d+\.\d+)pt", log)
        if ok:
            shutil.copy(build / f"{p.stem}_preview.pdf", out / f"{p.stem}.pdf")
            big = [float(x) for x in over if float(x) > 2]
            status[p.stem] = "ok" + (f" (overfull by up to {max(big):.0f}pt at 6.5in)" if big else "")
        else:
            err = [l for l in log.splitlines() if l.startswith("!")][:2]
            status[p.stem] = "FAILED: " + " ".join(err)
    return status
