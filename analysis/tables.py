def texify(s) -> str:
    """esc() with known ASCII math fragments typeset as math."""
    s = str(s)
    parts = [s]
    for a, b in MATH:
        nxt = []
        for x in parts:
            if isinstance(x, tuple):
                nxt.append(x)
                continue
            bits = x.split(a)
            for k, bit in enumerate(bits):
                if k:
                    nxt.append((b,))
                nxt.append(bit)
        parts = nxt
    return "".join(x[0] if isinstance(x, tuple) else esc(x) for x in parts)


def num(v, d=3):
    if v is None or not np.isfinite(v):
        return "--"
    return f"{v:.{d}g}" if abs(v) < 1000 else f"{v:.0f}"


def pct(p, sig_mark=True):
    if not p or not np.isfinite(p.get("rel", np.nan)):
        return "--"
    s = f"{100 * p['rel']:+.0f}\\%"
    if sig_mark and p.get("better"):
        return r"\textbf{" + s + "}"
    if sig_mark and p.get("worse"):
        return r"\underline{" + s + "}"
    return s


def pci(p):
    """Change with its 95% CI. With >= 2 seeds the CI is a Student-t interval, symmetric about the
    point estimate, so it is printed exactly as +-half-width; a 1-seed bootstrap CI keeps [lo, hi]."""
    if not p:
        return "--"
    lo, hi = 100 * p["ci"][0], 100 * p["ci"][1]
    if p.get("ci_method") == "t-over-seeds":
        return f"{pct(p)} $\\pm${(hi - lo) / 2:.0f}"
    return f"{pct(p)} [{lo:+.0f}, {hi:+.0f}]"


def _write(out: Path, name: str, lines: list) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    p = out / f"{name}.tex"
    p.write_text("% generated by analysis/paper_results.py -- do not edit by hand\n"
                 "% requires \\usepackage{booktabs,longtable,array}\n" + "\n".join(lines) + "\n")
    return p


