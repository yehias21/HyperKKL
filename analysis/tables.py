         r"\caption{Deployment scorecard, realistic deployment (" + esc(nid) + r": partial model + 30\% parameter "
         r"error + AR(1) Student-$t$ sensor noise), dev systems, mean over seeds. Columns as in hyperkkl/tree.py "
         r"Groups: KKL (latent, lora, hyper), DATA-DRIVEN same-data baselines (nlox, koopman\_kf, greybox\_*), MODEL-BASED "
