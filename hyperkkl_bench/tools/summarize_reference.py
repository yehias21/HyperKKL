"""Summarise reference/runs/<baseline>/*.json into reference/runs/<baseline>/SUMMARY.md (one row per cell)."""
import json
import sys
from pathlib import Path

D = Path(__file__).resolve().parents[1] / "reference" / "runs"


def main(b="ekf_gated"):
    rows = ["| cell | id | shape_ood | seq_ood | outliers (seq) | burst (seq) | poor_init (seq) | div (clean, seq) | cov95 (seq) | ANEES (seq) | latency us |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    f = lambda v: "n/a" if v is None else f"{v:.4f}"
    for p in sorted((D / b).glob("*.json")):
        r = json.loads(p.read_text())
        R = r["results"]
        g = lambda s, c, k="nrmse_unmeasured": R.get(s, {}).get(c, {}).get("summary", {}).get(k)
        cal = R["test_sequence_ood"]["clean"].get("calibration") or {}
        rows.append(f"| {p.stem.replace('__', '/')} | {f(g('test_id', 'clean'))} | {f(g('test_shape_ood', 'clean'))} | "
                    f"{f(g('test_sequence_ood', 'clean'))} | {f(g('test_sequence_ood', 'outliers'))} | "
                    f"{f(g('test_sequence_ood', 'burst_outage'))} | {f(g('test_sequence_ood', 'poor_init'))} | "
                    f"{g('test_sequence_ood', 'clean', 'div_rate'):.2f} | {f(cal.get('coverage95'))} | "
                    f"{'n/a' if cal.get('anees') is None else format(cal['anees'], '.3g')} | "
                    f"{r['cost'].get('latency_us_median', float('nan')):.0f} |")
    hdr = [f"# Reference runs: `{b}` (settled unmeasured NRMSE, 64 episodes per tier, one deterministic run)", "",
           "Generated by tools/run_reference_filters.py + tools/summarize_reference.py. Full reports (per-episode, CIs, "
           "cost) in the JSON files next to this one.", ""]
    (D / b / "SUMMARY.md").write_text("\n".join(hdr + rows) + "\n")
    print("\n".join(rows[:5]), "...", len(rows) - 2, "cells")


if __name__ == "__main__":
    main(*sys.argv[1:])
