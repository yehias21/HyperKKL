"""Results for the bounded plants (PREREG.md) -> results.json, tables.md. Read-only on all runs.

    .venv/bin/python experiments/cartpole_bounded/analyze.py
"""
import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path("/mnt/raid0_gpu4/demo/data/papers/TMLR/hyperkkl")
TREE = ROOT / "experiments" / "tree"
HERE = ROOT / "experiments" / "cartpole_bounded"
SEEDS = [0, 1, 2]
TIERS = ["id", "shape_ood", "sequence_ood"]
GREYBOX = ("greybox_ekf", "greybox_ukf", "greybox_ekf_oracle")
PAIRS = {"cartpole_b": "cartpole", "two_link_arm_b": "two_link_arm"}
SOAP = {"cartpole_b": HERE / "soap_runs" / "TEST-C3-B" / "cartpole_b",
        "two_link_arm_b": HERE / "soap_runs" / "TEST-C3-B" / "two_link_arm_b",
        "cartpole": ROOT / "experiments" / "p2_rescore" / "runs" / "TEST-C3" / "cartpole"}


def tci(d):
    d = np.asarray(d, float); n = len(d)
    if n < 2:
        return [float("nan"), float("nan")]
    h = stats.t.ppf(0.975, n - 1) * d.std(ddof=1) / math.sqrt(n)
    return [float(math.exp(d.mean() - h)), float(math.exp(d.mean() + h))]


def tree_vals(node, plant):
    """{method: {tier: {'tot': [per seed], 'unm': [...], 'state': [[...] per seed]}}}"""
    out = {}
    nan = float("nan")
    for s in SEEDS:
        f = TREE / node / "runs" / plant / f"seed{s}" / "results.json"
        if not f.exists():
            return None
        r = json.loads(f.read_text())["results"]
        for t in TIERS:
            for m, sc in r[t]["clean"]["scorecard"].items():
                d = out.setdefault(m, {}).setdefault(t, {"tot": [nan] * s, "unm": [nan] * s, "state": []})
                d["tot"].append(sc["nrmse_mean"]); d["unm"].append(sc["nrmse_unmeasured"]); d["state"].append(sc["nrmse_state"])
    return out


def soap_vals(plant):
    out = {}
    for arm in ("A2", "A4"):
        for s in SEEDS:
            f = SOAP[plant] / f"seed{s}" / f"{arm}.json"
            if not f.exists():
                break
            r = json.loads(f.read_text())["results"]
            for t in TIERS:
                sc = r[t]["scorecard"]
                d = out.setdefault(arm, {}).setdefault(t, {"tot": [], "unm": [], "state": []})
                d["tot"].append(sc["nrmse_mean"]); d["unm"].append(sc["nrmse_unmeasured"]); d["state"].append(sc["nrmse_state"])
        else:
            continue
        out.pop(arm, None)                                 # incomplete arm
    return out


def folds(v, tier, key):
    gb = {m: v[m][tier][key] for m in GREYBOX if m in v}
    if not gb:
        return None
    gb = {m: v for m, v in gb.items() if len(v) == len(SEEDS) and np.isfinite(v).all()}
    if not gb:
        return None
    gbm = min(gb, key=lambda m: np.mean(gb[m])); g = np.array(gb[gbm])
    row = {"greybox": gbm, "greybox_mean": float(g.mean()), "greybox_seeds": g.tolist()}
    lh = min(("lora", "hyper"), key=lambda m: np.mean(v[m][tier][key]) if m in v else 9e9)
    for name, m in (("A2", "A2"), ("A4", "A4"), ("frozen_" + lh, lh)):
        if m not in v:
            continue
        a = np.array(v[m][tier][key])
        f, ci = float(a.mean() / g.mean()), tci(np.log(a / g))
        row[name] = {"mean": float(a.mean()), "seeds": a.tolist(), "fold": f, "fold_ci": ci,
                     "outcome": "win" if ci[1] < 1 else ("lose" if ci[0] > 1 else "tie")}
    return row


def budget(plant, tier):
    if plant in PAIRS:
        b = json.loads((HERE / f"budget_{plant}.json").read_text())
        d = b["dists"]["eval_id" if tier == "id" else "eval_seq"]["c3"]["bayes"]; a = b["alpha"]
    else:
        b = json.loads((ROOT / "experiments" / "information" / "budgets_c3.json").read_text())[plant]
        d = b["dists"]["eval_id" if tier == "id" else "eval_seq"]["c3"]["bayes"]; a = b["alpha"]
    return d["windows"][f"{3 / a:g}"]["unmeasured_lb"], d["full"]["unmeasured_lb"]


def main():
    res, L = {}, ["# Bounded plants: results (generated by analyze.py; nothing hand-edited)", ""]
    for plant in ["cartpole_b", "two_link_arm_b", "cartpole", "two_link_arm"]:
        old = plant not in PAIRS
        c3 = tree_vals("TEST-C3" if old else "TEST-C3-B", plant)
        c1 = tree_vals("TEST-C1" if old else "TEST-C1-B", plant)
        if c3 is None:
            L.append(f"## {plant}: TEST-C3 runs incomplete"); continue
        if plant in SOAP:
            c3.update(soap_vals(plant))
        res[plant] = {"C3": c3, "C1": c1, "folds": {}, "bits": {}}
        L += [f"## {plant} ({'old, TEST-C3/TEST-C1' if old else 'new, TEST-C3-B/TEST-C1-B'})", "",
              "TEST-C3 setting, seed mean NRMSE (1 = climatology): total | unmeasured | per state", "",
              "| method | " + " | ".join(TIERS) + " |", "|---|" + "---|" * len(TIERS)]
        for m in sorted(c3, key=lambda m: np.mean(c3[m]["sequence_ood"]["tot"])):
            cells = []
            for t in TIERS:
                d = c3[m][t]
                cells.append(f"{np.mean(d['tot']):.4f} / {np.mean(d['unm']):.4f} / [{', '.join(f'{x:.3f}' for x in np.mean(d['state'], 0))}]")
            L.append(f"| {m} | " + " | ".join(cells) + " |")
        if c1:
            L += ["", "TEST-C1 setting (exact model, white noise), total NRMSE seed mean:", "",
                  "| method | " + " | ".join(TIERS) + " |", "|---|" + "---|" * len(TIERS)]
            for m in sorted(c1, key=lambda m: np.mean(c1[m]["sequence_ood"]["tot"])):
                L.append(f"| {m} | " + " | ".join(f"{np.mean(c1[m][t]['tot']):.4f} (unm {np.mean(c1[m][t]['unm']):.4f})" for t in TIERS) + " |")
        L += ["", "HyperKKL vs best grey-box (fold = HyperKKL / grey-box, 95% CI paired over seeds):", "",
              "| tier | metric | grey-box | gb mean | arm | mean | fold [CI] | outcome |", "|---|---|---|---|---|---|---|---|"]
        for t in ("id", "sequence_ood"):
            for key in ("unm", "tot"):
                f = folds(c3, t, key)
                if f is None:
                    continue
                res[plant]["folds"][f"{t}/{key}"] = f
                for arm in [k for k in f if k.startswith(("A2", "A4", "frozen"))]:
                    a = f[arm]
                    L.append(f"| {t} | {key} | {f['greybox']} | {f['greybox_mean']:.4f} | {arm} | {a['mean']:.4f} | "
                             f"{a['fold']:.2f} [{a['fold_ci'][0]:.2f}, {a['fold_ci'][1]:.2f}] | {a['outcome']} |")
            try:
                A, full = budget(plant, t)
            except Exception:
                continue
            f = res[plant]["folds"].get(f"{t}/unm")
            if f:
                arms = [k for k in f if k.startswith(("A2", "A4"))] or [k for k in f if k.startswith("frozen")]
                best = min(arms, key=lambda k: f[k]["fold"])
                pred = "CANNOT win" if A > f["greybox_mean"] else "can win"
                out = f[best]["outcome"]
                res[plant]["bits"][t] = {"A": A, "full": full, "eps": f["greybox_mean"], "pred": pred, "arm": best,
                                         "fold": f[best]["fold"], "outcome": out,
                                         "violates": pred == "CANNOT win" and out == "win"}
        if res[plant]["bits"]:
            L += ["", "Bits rule (A = window 3/alpha unmeasured bound, corrected method):", "",
                  "| tier | A | full-past | eps (grey-box unm) | prediction | best SOAP arm fold | outcome | violation |", "|---|---|---|---|---|---|---|---|"]
            for t, b in res[plant]["bits"].items():
                L.append(f"| {t} | {b['A']:.4f} | {b['full']:.4f} | {b['eps']:.4f} | {b['pred']} | {b['arm']} {b['fold']:.2f} | {b['outcome']} | {'YES' if b['violates'] else 'no'} |")
        L.append("")
    (HERE / "results.json").write_text(json.dumps(res, indent=1))
    (HERE / "tables.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
