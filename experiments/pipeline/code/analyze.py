"""Mechanical verdicts of experiments/pipeline/PREREG.md -> experiments/pipeline/RESULTS.md (+ results_summary.json)."""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hyperkkl.metrics import paired_relative  # noqa: E402

LIVE = Path("/mnt/raid0_gpu4/demo/data/papers/TMLR/hyperkkl")
OUT = LIVE / "experiments" / "pipeline"
SYSTEMS = ["battery", "bioreactor", "duffing", "lorenz", "quad_tank", "vdp"]
SCEN = ["C3-partial", "C3-mismatch30", "C1-where"]
TIERS = ["sequence_ood", "shape_ood", "id"]
SEEDS = [0, 1, 2]
DATA = ["nlox", "koopman_kf", "koopman_kf_bilinear", "greybox_ekf", "greybox_ukf", "greybox_ekf_oracle"]
ARMKINDS = ["P1-lora", "P1-hyper", "P2-lora", "P2-hyper", "P4-lora", "P4-hyper", "P3"]


def load(sc, s):
    """per seed: {method: {tier: nrmse array}} merged from the pipeline run and the tree run."""
    per = []
    for k in SEEDS:
        pf = OUT / "runs" / sc / s / f"seed{k}" / "results.json"
        if not pf.exists():
            return None
        p = json.load(open(pf))
        t = json.load(open(LIVE / "experiments" / "tree" / sc / "runs" / s / f"seed{k}" / "results.json"))
        m = {}
        for tier in TIERS:
            fp, ft = p["results"][tier]["clean"]["families"], t["results"][tier]["clean"]["families"]
            assert fp == ft, (sc, s, k, tier)
            for name, d in t["results"][tier]["clean"]["methods"].items():
                m.setdefault("tree:" + name, {})[tier] = np.asarray(d["nrmse"], float)
            for name, d in p["results"][tier]["clean"]["methods"].items():
                m.setdefault(name, {})[tier] = np.asarray(d["nrmse"], float)
        per.append({"m": m, "p": p})
    return per


def smean(per, name, tier):
    return float(np.mean([r["m"][name][tier].mean() for r in per]))


def pr(per, a, b, tier):
    return paired_relative([r["m"][a][tier] for r in per], [r["m"][b][tier] for r in per])


def best(per, names, tier):
    have = [n for n in names if all(n in r["m"] for r in per)]
    return min(have, key=lambda n: smean(per, n, tier)) if have else None


def fmt(q):
    if not q:
        return "-"
    s = "*" if (q["better"] or q["worse"]) else ""
    return f"{100 * q['rel']:+.0f}% [{100 * q['ci'][0]:+.0f}, {100 * q['ci'][1]:+.0f}]{s}"


summary = {"cells": {}, "verdicts": {}, "gap": {}}
lines = ["# Pipeline study: results (mechanical verdicts of PREREG.md)", "",
         "Generated by `analyze.py` (scratch copy; mirrored in `experiments/pipeline/code/`) from "
         "`experiments/pipeline/runs/*/*/seed*/results.json` plus the tree runs they pair with. "
         "Relative change of mean episode NRMSE vs the reference, Student-t 95% CI over seeds 0-2, "
         "`*` = CI excludes 0. Negative = the arm is better.", ""]
done = {(sc, s): load(sc, s) for sc in SCEN for s in SYSTEMS}
n_done = sum(v is not None for v in done.values())
lines.append(f"Cells complete (all 3 seeds): {n_done}/{len(done)}.")
lines.append("")

for sc in SCEN:
    lines += [f"## {sc}", ""]
    arms = [a for a in ARMKINDS if not (a.startswith("P4") and sc == "C1-where")]
    for tier in TIERS:
        lines += [f"### {tier}", "", "| system | P0-lora | P0-hyper | autonomous | " + " | ".join(arms) + " |",
                  "|" + "---|" * (4 + len(arms))]
        for s in SYSTEMS:
            per = done[(sc, s)]
            if per is None:
                lines.append(f"| {s} | PENDING |" + " |" * (3 + len(arms)))
                continue
            p0b = best(per, ["P0-lora", "P0-hyper"], tier)
            row = [s, f"{smean(per, 'P0-lora', tier):.4f}", f"{smean(per, 'P0-hyper', tier):.4f}",
                   f"{smean(per, 'autonomous', tier):.3f}"]
            for a in arms:
                ref = p0b if a == "P3" else "P0-" + a.split("-")[1]
                q = pr(per, a, ref, tier)
                summary["cells"].setdefault(sc, {}).setdefault(s, {}).setdefault(tier, {})[a] = \
                    {"vs": ref, "nrmse": smean(per, a, tier), **q}
                row.append(f"{smean(per, a, tier):.4f} {fmt(q)}")
            lines.append("| " + " | ".join(row) + " |")
        lines += ["", f"(P1/P2/P4-k vs P0-k; P3 vs the better P0 kind.)", ""]

    # verdicts (sequence_ood)
    lines += [f"### Verdicts ({sc}, sequence_ood; BETTER = CI in favour on >= 4/6 and worse on none)", "",
              "| arm | better on | worse on | n systems | verdict | shape_ood better/worse | id better/worse |", "|---|---|---|---|---|---|---|"]
    for a in arms:
        res = {}
        for tier in TIERS:
            c = [summary["cells"].get(sc, {}).get(s, {}).get(tier, {}).get(a) for s in SYSTEMS]
            c = [(s, x) for s, x in zip(SYSTEMS, c) if x]
            res[tier] = ([s for s, x in c if x["better"]], [s for s, x in c if x["worse"]], len(c))
        b, w, n = res["sequence_ood"]
        if n < 6:
            v = f"PENDING ({n}/6)" if (len(b) < 4 or w) and not (len(w) >= 4 and not b) else None
        v = None
        if len(b) >= 4 and not w:
            v = "BETTER"
        elif len(w) >= 4 and not b:
            v = "WORSE"
        else:
            v = "NOT BETTER" if n == 6 else f"INCOMPLETE ({n}/6)"
        if n < 6 and v in ("BETTER", "WORSE"):
            v += f"* ({n}/6)"
        summary["verdicts"].setdefault(sc, {})[a] = {"verdict": v, "better": b, "worse": w, "n": n}
        lines.append(f"| {a} | {len(b)} {b} | {len(w)} {w} | {n} | **{v}** | "
                     f"{len(res['shape_ood'][0])}/{len(res['shape_ood'][1])} | {len(res['id'][0])}/{len(res['id'][1])} |")
    lines.append("")

    # P3 vs autonomous, P3 vs tree latent/concat (C1), lora vs hyper ordering
    lines += [f"### Controls ({sc}, sequence_ood)", "",
              "| system | P3 vs autonomous | P3 vs P1-best | P1-hyper vs P1-lora | P2-hyper vs P2-lora | P0-hyper vs P0-lora |"
              + (" P3 vs tree latent | P3 vs tree concat |" if sc == "C1-where" else ""),
              "|---|---|---|---|---|---|" + ("---|---|" if sc == "C1-where" else "")]
    for s in SYSTEMS:
        per = done[(sc, s)]
        if per is None:
            continue
        t = "sequence_ood"
        p1b = best(per, ["P1-lora", "P1-hyper"], t)
        row = [s, fmt(pr(per, "P3", "autonomous", t)), fmt(pr(per, "P3", p1b, t)),
               fmt(pr(per, "P1-hyper", "P1-lora", t)), fmt(pr(per, "P2-hyper", "P2-lora", t)),
               fmt(pr(per, "P0-hyper", "P0-lora", t))]
        if sc == "C1-where":
            row += [fmt(pr(per, "P3", "tree:latent", t)), fmt(pr(per, "P3", "tree:concat", t))]
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")

    # gap to the best data-driven baseline
    if sc != "C1-where":
        lines += [f"### Gap to the best data-driven baseline ({sc}, sequence_ood)", "",
                  "| system | best data-driven | P0-best vs it | loss cell | " + " | ".join(
                      ["P1", "P2", "P3", "P4"]) + " |", "|---|---|---|---|---|---|---|---|"]
        for s in SYSTEMS:
            per = done[(sc, s)]
            if per is None:
                continue
            t = "sequence_ood"
            cands = ["tree:" + d for d in DATA] + [d for d in DATA]
            bd = best(per, cands, t)
            p0b = best(per, ["P0-lora", "P0-hyper"], t)
            q0 = pr(per, p0b, bd, t)
            loss = q0["worse"]
            row = [s, f"{bd.replace('tree:', '')} {smean(per, bd, t):.4f}", f"{p0b} {fmt(q0)}", "yes" if loss else "no"]
            g = {"baseline": bd, "p0": q0, "loss_cell": loss, "arms": {}}
            for arm in ["P1", "P2", "P3", "P4"]:
                names = [arm] if arm == "P3" else [f"{arm}-lora", f"{arm}-hyper"]
                ab = best(per, names, t)
                qa, qn = pr(per, ab, bd, t), pr(per, ab, p0b, t)
                closes = loss and not qa["worse"]
                narrows = loss and qn["better"]
                g["arms"][arm] = {"best": ab, "vs_baseline": qa, "vs_p0": qn, "closes": closes, "narrows": narrows}
                row.append(f"{ab} {smean(per, ab, t):.4f}: vs base {fmt(qa)}"
                           + (" CLOSES" if closes else (" narrows" if narrows else "")))
            summary["gap"].setdefault(sc, {})[s] = g
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

# collapse, params, compute
lines += ["## Zero-input collapse, parameters, compute (seed means over finished runs)", "",
          "| scenario | system | arm | exact vs phase-1 base | max dev (sigma) | zero-input NRMSE | autonomous zero-input NRMSE | trainable total | conditioner | wall train (s) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
for sc in SCEN:
    for s in SYSTEMS:
        per = done[(sc, s)]
        if per is None:
            continue
        for a in ["P0-lora", "P0-hyper", "P1-lora", "P1-hyper", "P2-lora", "P2-hyper", "P3", "P4-lora", "P4-hyper"]:
            if a not in per[0]["p"]["collapse"]:
                continue
            cs = [r["p"]["collapse"][a]["vs_phase1_base"] for r in per]
            inf = [r["p"]["info"].get(a, {}) for r in per]
            wall = [r["p"]["wall_s"].get(a.replace("-", "." if a.startswith("P1") or a.startswith("P2") else ".p2."), np.nan)
                    if not a.startswith("P0") else np.nan for r in per]
            lines.append(f"| {sc} | {s} | {a} | {all(c.get('exact') for c in cs)} | {np.mean([c.get('max_abs_dev_sigma', np.nan) for c in cs]):.3g} | "
                         f"{np.mean([c['zero_input_nrmse'] for c in cs]):.4f} | {np.mean([r['p']['collapse']['autonomous']['zero_input_nrmse'] for r in per]):.4f} | "
                         f"{inf[0].get('trainable_total', '-')} | {inf[0].get('n_params', '-')} | {np.nanmean(wall):.0f} |")
lines.append("")
plan = next((v[0]["p"]["compute_plan"] for v in done.values() if v), None)
if plan:
    lines += ["Compute plan (loss-batch gradient evaluations per arm): " +
              ", ".join(f"{a}: {d['units']} ({d['opt_steps']} optimiser steps)" for a, d in plan.items()), ""]
rep = [max(r["p"]["p0_repro"].values()) for v in done.values() if v for r in v]
if rep:
    lines += [f"P0 reproduction vs the tree runs: max relative per-episode NRMSE difference {max(rep):.2e} over {len(rep)} runs.", ""]
p4 = [(sc, s, r["p"]["info"]["phase1_P4"], r["p"]["info"]["phase1_P0"]) for (sc, s), v in done.items() if v
      for r in v if "phase1_P4" in r["p"]["info"]]
if p4:
    lines += ["P4 phase-1 diagnostics vs P0 (seed 0..2 pooled, per scenario/system means):", "",
              "| scenario | system | median rel. change of f0 | eps_pde_rms P0 -> P4 | eps_dec P0 -> P4 | l_dec_q95 P0 -> P4 |", "|---|---|---|---|---|---|"]
    agg = {}
    for sc, s, a4, a0 in p4:
        agg.setdefault((sc, s), []).append((a4, a0))
    for (sc, s), L in agg.items():
        m = lambda f: np.mean([f(x) for x in L])
        lines.append(f"| {sc} | {s} | {m(lambda x: x[0]['f0_rel_change']):.3f} | {m(lambda x: x[1]['diag']['eps_pde_rms']):.3g} -> {m(lambda x: x[0]['diag']['eps_pde_rms']):.3g} | "
                     f"{m(lambda x: x[1]['diag']['eps_dec']):.3g} -> {m(lambda x: x[0]['diag']['eps_dec']):.3g} | {m(lambda x: x[1]['diag']['l_dec_q95']):.0f} -> {m(lambda x: x[0]['diag']['l_dec_q95']):.0f} |")
    lines.append("")
(OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")
json.dump(summary, open(OUT / "results_summary.json", "w"), indent=1, default=float)
print("\n".join(lines))
