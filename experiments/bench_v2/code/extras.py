from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

import analyze as A

HERE = A.HERE


def tci(lr):
    lr = np.asarray(lr, float)
    if len(lr) < 2:
        return float(np.exp(lr.mean())), [None, None]
    se = lr.std(ddof=1) / math.sqrt(len(lr))
    q = stats.t.ppf(0.975, len(lr) - 1)
    return float(np.exp(lr.mean())), [float(np.exp(lr.mean() - q * se)), float(np.exp(lr.mean() + q * se))]


def paired(ps, a, b):
    """ps: per_seed dict {obs: {seed: v}} -> ratio a / b, mean and 95 % t-CI over common seeds."""
    if a not in ps or b not in ps:
        return None
    s = [k for k in ps[a] if k in ps[b] and ps[a][k] > 0 and ps[b][k] > 0]
    if not s:
        return None
    r, ci = tci([math.log(ps[a][k] / ps[b][k]) for k in s])
    return {"ratio": r, "ci95": ci, "seeds": sorted(s)}


def main():
    sel = A.load()
    cells, src = A.table(sel)
    out, L = {}, ["# bench_v2 secondary comparisons (generated by code/extras.py)", ""]

    def ps_of(key, block):
        co = cells.get(key, {})
        seeds = sorted({s for o, bs in co.items() if o not in A.DETERMINISTIC for s in bs}) or [0]
        return A.per_seed(co, block, seeds)

    # 1. Lorenz-96 equal data: ude32 / ude1 (+ EKF / UKF) vs hyperkkl, op_ood and legacy tiers
    k = ("driven", "lorenz96", "realistic")
    L += ["## Lorenz-96 (driven, realistic, equal mixed data): grey-box / hyperkkl, per-seed ratio [95 % t-CI]", "",
          "| block | " + " | ".join(["ude32_ekf", "ude32_ukf", "ude1_ekf", "ude1_ukf", "node32_ekf"]) + " |", "|---|---|---|---|---|---|"]
    o1 = {}
    for blk in ("test_op_ood/clean", "test_op_id/clean", "test_legacy_id/clean", "test_legacy_sequence_ood/clean"):
        ps = ps_of(k, blk)
        row = []
        for m in ("ude32_ekf_gated", "ude32_ukf_gated", "ude1_ekf_gated", "ude1_ukf_gated", "node32_ekf_gated"):
            r = paired(ps, m, "hyperkkl")
            o1.setdefault(blk, {})[m] = r
            row.append("-" if r is None else f"{r['ratio']:.3g} [{r['ci95'][0]:.3g}, {r['ci95'][1]:.3g}]" if r['ci95'][0] else f"{r['ratio']:.3g}")
        L.append(f"| {blk} | " + " | ".join(row) + " |")
    out["lorenz96_greybox_vs_hyperkkl"] = o1
    L.append("")

    # 2. network C5: cost (extra phase-2 wall time) and accuracy hyperkkl / hk_base, both families
    L += ["## network: C5 cost and effect (hyperkkl = hk_base + C5)", "",
          "| cell | C5 extra train / base train (wall) | clean primary ratio C5/base | outliers ratio C5/base |", "|---|---|---|---|"]
    o2 = {}
    for key, blk, outl in ((("driven", "network", "realistic"), "test_op_ood/clean", "test_op_ood/outliers"),
                           (("autonomous", "network", "white"), "test_id/clean", "test_id/outliers")):
        walls = []
        for f in (HERE / "runs" / key[0] / key[1] / key[2]).glob("hk_lr*/seed*.json"):
            d = json.loads(f.read_text())
            m = d["meta"]["hyperkkl"]
            walls.append(m["c5_extra_wall_s"] / max(m["base_wall_s"], 1e-9))
        a = paired(ps_of(key, blk), "hyperkkl", "hk_base")
        b = paired(ps_of(key, outl), "hyperkkl", "hk_base")
        o2["/".join(key)] = {"c5_wall_over_base": [float(np.mean(walls)), float(np.min(walls)), float(np.max(walls))] if walls else None,
                             "clean": a, "outliers": b}
        fm = lambda r: "-" if r is None else f"{r['ratio']:.3g}" + (f" [{r['ci95'][0]:.3g}, {r['ci95'][1]:.3g}]" if r['ci95'][0] else "")
        L.append(f"| {'/'.join(key)} | {np.mean(walls):.2f} (range {np.min(walls):.2f}-{np.max(walls):.2f}, n {len(walls)})" if walls else f"| {'/'.join(key)} | -")
        L[-1] += f" | {fm(a)} | {fm(b)} |"
    out["network_c5"] = o2
    L.append("")

    # 3. family A: hyperkkl vs autonomous KKL at equal budget (nlox_m, injection = 0 at u = 0), vs auto, vs dkkl_m
    L += ["## Family A: is autonomous HyperKKL ~ an autonomous KKL? (test_id/clean; prediction: hyperkkl / nlox_m in [0.67, 1.5])", "",
          "| cell | hyperkkl / nlox_m | hyperkkl / dkkl_m | hyperkkl / auto | hyperkkl / hk_base | within [0.67, 1.5]? |", "|---|---|---|---|---|---|"]
    o3, n_in, n_all = {}, 0, 0
    for key in sorted(c for c in cells if c[0] == "autonomous"):
        ps = ps_of(key, "test_id/clean")
        r = {m: paired(ps, "hyperkkl", m) for m in ("nlox_m", "dkkl_m", "auto", "hk_base")}
        o3["/".join(key)] = r
        within = None
        if r["nlox_m"]:
            within = 0.67 <= r["nlox_m"]["ratio"] <= 1.5
            n_in += within; n_all += 1
        fm = lambda x: "-" if x is None else f"{x['ratio']:.3g}"
        L.append(f"| {key[1]} | {fm(r['nlox_m'])} | {fm(r['dkkl_m'])} | {fm(r['auto'])} | {fm(r['hk_base'])} | {within} |")
    L += ["", f"cells within [0.67, 1.5]: {n_in} of {n_all} (prediction: >= 5 of 7)", ""]
    out["autonomous_equivalence"] = {"cells": o3, "within": n_in, "of": n_all}

    # 4. driven op_ood / op_id ratio per method (median over cells) and legacy-vs-operating rank agreement
    L += ["## Driven: op_ood / op_id ratio (median over cells, seed means) and rank agreement legacy vs operating tiers", ""]
    ratios, taus = {}, []
    for key in sorted(c for c in cells if c[0] == "driven"):
        po, pi = ps_of(key, "test_op_ood/clean"), ps_of(key, "test_op_id/clean")
        pl = ps_of(key, "test_legacy_sequence_ood/clean")
        mo = {m: np.nanmean(list(v.values())) for m, v in po.items() if v}
        mi = {m: np.nanmean(list(v.values())) for m, v in pi.items() if v}
        ml = {m: np.nanmean(list(v.values())) for m, v in pl.items() if v}
        for m in mo:
            if m in mi and mi[m] > 0:
                ratios.setdefault(m, []).append(mo[m] / mi[m])
        common = [m for m in mo if m in ml]
        if len(common) >= 4:
            t = stats.kendalltau([mo[m] for m in common], [ml[m] for m in common]).statistic
            taus.append((key[1], float(t), len(common)))
    L += ["| method | median op_ood / op_id | cells |", "|---|---|---|"]
    for m in sorted(ratios, key=lambda m: np.median(ratios[m])):
        L.append(f"| {m} | {np.median(ratios[m]):.3g} | {len(ratios[m])} |")
    L += ["", "Kendall tau between the method ranking on test_op_ood and on test_legacy_sequence_ood, per cell:", ""]
    L += [f"* {p}: tau {t:.2f} ({n} methods)" for p, t, n in taus]
    out["op_ratio"] = {m: float(np.median(v)) for m, v in ratios.items()}
    out["rank_agreement_legacy_vs_op"] = taus
    L.append("")

    # 5. drone outliers (equal mixed data): compiled from experiments/equaldata_mix (not a bench_v2 run)
    try:
        q = json.loads((HERE.parent / "equaldata_mix" / "results.json").read_text())["quad"]
        hk = q["hk"]["default+C5"]
        L += ["## Drone (quad_planar, Case A realistic) under outliers, equal mixed data: compiled from experiments/equaldata_mix "
              "(5 seeds; not rerun here)", "", "| method | id/outliers | id/clean | ratio to HyperKKL default (outliers) [95 % t-CI] |",
              "|---|---|---|---|"]
        o5 = {}
        for m in ("ude5k_ukf", "ude5k_ekf", "ude5k1_ukf", "ude5k1_ekf"):
            c = q["cmp"][m]["mix"]
            a, b = c["id/outliers"].get("per_seed"), hk["id/outliers"]["per_seed"]
            r = tci([math.log(x / y) for x, y in zip(a, b)]) if a else (None, [None, None])
            o5[m] = {"outliers": c["id/outliers"]["mean"], "clean": c["id/clean"]["mean"], "ratio": r[0], "ci95": r[1]}
            L.append(f"| {m} (mixed data) | {c['id/outliers']['mean']:.4f} | {c['id/clean']['mean']:.4f} | "
                     + ("-" if r[0] is None else f"{r[0]:.3g} [{r[1][0]:.3g}, {r[1][1]:.3g}]") + " |")
        L.append(f"| HyperKKL default (A3 + mix + C5) | {hk['id/outliers']['mean']:.4f} | {hk['id/clean']['mean']:.4f} | 1 |")
        out["drone_outliers_equaldata_mix"] = o5
    except Exception as ex:                                     # pragma: no cover
        L.append(f"drone outliers: not compiled ({ex})")
    L.append("")
    # 6. family A secondary tiers (PROTOCOL 8.0): test_ic_ood (settled unmeasured + transient all-state) and
    #    test_param_shift; methods that used phase1 (envelope-wide zero-input episodes, which include the IC shell) flagged
    P1 = {"hyperkkl", "hk_base", "auto", "ude1_ekf_gated", "ude1_ukf_gated", "ude32_ekf_gated", "ude32_ukf_gated"}
    meths = ["hyperkkl", "hk_base", "ude32_ukf_gated", "ude1_ekf_gated", "gru", "nlox_m", "dkkl_m", "ekf_gated_tuned", "auto"]
    L += ["## Family A secondary tiers (seed means; * = the method also trained on phase1, whose envelope-wide ICs "
          "overlap the test_ic_ood shell, so its ic_ood number is NOT out-of-distribution)", ""]
    o6 = {}
    for key in sorted(c for c in cells if c[0] == "autonomous"):
        L += [f"### {key[1]}", "", "| method | test_id | test_ic_ood (settled unm.) | test_ic_ood (transient, all states) | test_param_shift |",
              "|---|---|---|---|---|"]
        for m in meths:
            vals = []
            for blk, met in (("test_id/clean", "nrmse_unmeasured"), ("test_ic_ood/clean", "nrmse_unmeasured"),
                             ("test_ic_ood/clean", "nrmse_transient"), ("test_param_shift/clean", "nrmse_unmeasured")):
                co = cells[key].get(m, {})
                if m in A.DETERMINISTIC:
                    v = [A.value(co[0], blk, met)] if 0 in co else []
                else:
                    v = [A.value(b, blk, met) for b in co.values()]
                v = [x for x in v if np.isfinite(x)]
                vals.append(float(np.mean(v)) if v else float("nan"))
            o6.setdefault("/".join(key), {})[m] = vals
            L.append(f"| {m}{'*' if m in P1 else ''} | " + " | ".join(f"{x:.4g}" for x in vals) + " |")
        L.append("")
    out["autonomous_secondary_tiers"] = o6

    # 7. driven robustness: seed means on the non-clean blocks
    blocks = ["test_op_ood/clean", "test_op_ood/outliers", "test_op_ood/burst_outage", "test_op_ood/input_realistic",
              "test_op_id/poor_init", "test_op_id/input_cmd_vs_applied", "test_op_id/input_quant"]
    L += ["## Driven: robustness blocks (seed means of settled unmeasured NRMSE)", ""]
    o7 = {}
    for key in sorted(c for c in cells if c[0] == "driven"):
        L += [f"### {key[1]}", "", "| method | " + " | ".join(b.replace("test_", "") for b in blocks) + " |",
              "|---|" + "---|" * len(blocks)]
        for m in meths[:-1]:
            co = cells[key].get(m, {})
            row = []
            for blk in blocks:
                v = [A.value(co[0], blk)] if (m in A.DETERMINISTIC and 0 in co) else [A.value(b, blk) for b in co.values()]
                v = [x for x in v if np.isfinite(x)]
                row.append(float(np.mean(v)) if v else float("nan"))
            o7.setdefault("/".join(key), {})[m] = row
            L.append(f"| {m} | " + " | ".join(f"{x:.4g}" for x in row) + " |")
        L.append("")
    out["driven_robustness"] = o7
    (HERE / "results_extras.json").write_text(json.dumps(out, indent=1, default=str))
    (HERE / "logs" / "extras.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
