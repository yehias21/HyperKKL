"""bench_v2 analysis (PREREG.md section 4).   python analyze.py  ->  results.json, logs/tables.md

Per (family, cell, observer, seed): among every run file that contains the observer (its lr configurations), keep the
one with the smallest validation score (val + val_ood; never a test block). Filters are deterministic: their seed-0
value stands for every seed. Primary block: B test_op_ood/clean, A test_id/clean. Statistics: per-seed log ratio to
hyperkkl, mean and 95 % t-interval, Holm over the cells of a family per method; ranks by seed mean.
"""
from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy import stats

HERE = Path(__file__).resolve().parent.parent
RUNS = HERE / "runs"
PRIMARY = {"driven": "test_op_ood/clean", "autonomous": "test_id/clean"}
DETERMINISTIC = {"ekf", "ukf", "ekf_gated", "ukf_gated", "ekf_gated_tuned", "ukf_gated_tuned"}
METRIC = "nrmse_unmeasured"
REF = "hyperkkl"


def load():
    sel = {}                                   # (fam, plant, var, obs, seed) -> (val_score, blocks, file, meta)
    for f in RUNS.glob("*/*/*/*/seed*.json"):
        fam, plant, var, tag = f.parts[-5:-1]
        if fam == "real" or tag.endswith("_smoke"):
            continue
        d = json.loads(f.read_text())
        for o, r in d["observers"].items():
            k = (fam, plant, var, o, int(d["seed"]))
            v = r["val_score"]
            v = v if np.isfinite(v) else 1e9
            if k not in sel or v < sel[k][0]:
                sel[k] = (v, r["blocks"], str(f.relative_to(HERE)), d.get("meta", {}).get(o, {}))
    return sel


def table(sel):
    cells = defaultdict(lambda: defaultdict(dict))       # (fam, plant, var) -> obs -> seed -> blocks
    src = defaultdict(dict)
    for (fam, plant, var, o, s), (v, b, f, m) in sel.items():
        cells[(fam, plant, var)][o][s] = b
        src[(fam, plant, var, o)][s] = {"file": f, "val": v, "lr": m.get("lr")}
    return cells, src


def value(b, block, metric=METRIC):
    if block not in b:
        return float("nan")
    return float(np.mean(b[block][metric]))


def per_seed(cell_obs, block, seeds):
    out = {}
    for o, bs in cell_obs.items():
        if o in DETERMINISTIC and 0 in bs:
            out[o] = {s: value(bs[0], block) for s in seeds}
        else:
            out[o] = {s: value(bs[s], block) for s in seeds if s in bs}
    return out


def holm(p):
    p = np.asarray(p, float)
    idx = np.argsort(p)
    m, adj, run = len(p), np.empty(len(p)), 0.0
    for r, i in enumerate(idx):
        run = max(run, min(1.0, (m - r) * p[i]))
        adj[i] = run
    return adj


def analyse():
    sel = load()
    cells, src = table(sel)
    res = {"cells": {}, "families": {}}
    lines = ["# bench_v2 results tables (generated by code/analyze.py)", ""]
    for fam in ("driven", "autonomous"):
        fam_cells = sorted(k for k in cells if k[0] == fam)
        if not fam_cells:
            continue
        block = PRIMARY[fam]
        pair = defaultdict(list)                          # method -> [(cell, mean log ratio, se, df, p)]
        ranks = defaultdict(list)
        best = {}
        lines += [f"## family {fam}: primary block {block}, metric settled {METRIC} (seed mean +- sd [n seeds])", ""]
        for key in fam_cells:
            co = cells[key]
            seeds = sorted({s for o, bs in co.items() if o not in DETERMINISTIC for s in bs}) or [0]
            ps = per_seed(co, block, seeds)
            summ = {}
            for o, d in ps.items():
                v = np.array([d[s] for s in sorted(d)], float)
                v = v[np.isfinite(v)]
                if len(v):
                    summ[o] = {"mean": float(v.mean()), "sd": float(v.std(ddof=1)) if len(v) > 1 else 0.0, "n": int(len(v)),
                               "per_seed": {int(s): d[s] for s in d},
                               "lr": {int(s): src[key + (o,)].get(s, {}).get("lr") for s in d}}
            order = sorted(summ, key=lambda o: summ[o]["mean"])
            for i, o in enumerate(order):
                ranks[o].append(i + 1)
            best["/".join(key[1:])] = order[0] if order else None
            if REF in ps:
                for o, d in ps.items():
                    if o == REF:
                        continue
                    common = [s for s in d if s in ps[REF] and np.isfinite(d[s]) and np.isfinite(ps[REF][s])
                              and d[s] > 0 and ps[REF][s] > 0]
                    if len(common) < 2:
                        continue
                    lr = np.array([math.log(d[s] / ps[REF][s]) for s in common])
                    se = lr.std(ddof=1) / math.sqrt(len(lr))
                    t = lr.mean() / se if se > 0 else math.copysign(1e9, lr.mean())
                    p = float(2 * stats.t.sf(abs(t), len(lr) - 1))
                    pair[o].append(("/".join(key[1:]), float(lr.mean()), float(se), len(lr) - 1, p))
            extra = {}
            for o, bs in co.items():
                b0 = bs.get(0) or next(iter(bs.values()))
                extra[o] = {bn: float(np.mean(bb[METRIC])) for bn, bb in b0.items()}
            res["cells"]["/".join(key)] = {"summary": summ, "order": order, "blocks_seed0": extra}
            ref_rank = order.index(REF) + 1 if REF in order else None
            lines.append(f"### {key[1]} / {key[2]}  (best: {order[0] if order else '-'}; hyperkkl rank {ref_rank} of {len(order)})")
            lines.append("")
            lines.append("| rank | method | " + METRIC + " | lr per seed |")
            lines.append("|---|---|---|---|")
            for i, o in enumerate(order):
                s = summ[o]
                lr = ",".join("-" if v is None else f"{v:g}" for v in s["lr"].values())
                lines.append(f"| {i + 1} | {o} | {s['mean']:.4g} +- {s['sd']:.2g} [{s['n']}] | {lr} |")
            lines.append("")
        # paired vs hyperkkl, Holm within the family per method
        lines += [f"### paired vs hyperkkl ({fam}): log ratio method / hyperkkl per seed, mean [95 % t-CI]; Holm over cells", "",
                  "| method | cells | better | tie | worse | geo-mean ratio |", "|---|---|---|---|---|---|"]
        fam_pair = {}
        for o, rows in sorted(pair.items()):
            adj = holm([r[4] for r in rows])
            bt = wt = tie = 0
            det = []
            for (c, m, se, df, p), pa in zip(rows, adj):
                q = stats.t.ppf(0.975, df) if df > 0 else float("inf")
                verdict = "tie"
                if pa < 0.05:
                    verdict = "better" if m < 0 else "worse"
                bt += verdict == "better"; wt += verdict == "worse"; tie += verdict == "tie"
                det.append({"cell": c, "ratio": math.exp(m), "ci": [math.exp(m - q * se), math.exp(m + q * se)],
                            "p": p, "p_holm": float(pa), "verdict": verdict})
            gm = math.exp(np.mean([r[1] for r in rows]))
            fam_pair[o] = {"better": bt, "tie": tie, "worse": wt, "geo_mean_ratio": gm, "cells": det}
            lines.append(f"| {o} | {len(rows)} | {bt} | {tie} | {wt} | {gm:.3g} |")
        lines.append("")
        rk = {o: {"median_rank": float(np.median(v)), "cells": len(v), "wins": int(sum(1 for x in v if x == 1))}
              for o, v in ranks.items()}
        res["families"][fam] = {"primary_block": block, "best_per_cell": best, "ranks": rk, "paired_vs_hyperkkl": fam_pair}
        lines += [f"### ranks ({fam})", "", "| method | median rank | cells | wins |", "|---|---|---|---|"]
        for o in sorted(rk, key=lambda o: rk[o]["median_rank"]):
            lines.append(f"| {o} | {rk[o]['median_rank']:.1f} | {rk[o]['cells']} | {rk[o]['wins']} |")
        lines.append("")
    # real tracks
    real = {}
    for f in sorted((RUNS / "real").glob("*/*/seed*.json")):
        ds, m = f.parts[-3], f.parts[-2]
        if m.endswith("_smoke"):
            continue
        d = json.loads(f.read_text())
        real.setdefault(ds, {}).setdefault(m, {})[int(d["seed"])] = d["meta"].get("headline")
    if real:
        lines += ["## real tracks: track headline (seed mean +- sd [n])", "", "| track | method | headline |", "|---|---|---|"]
        for ds, ms in real.items():
            for m in sorted(ms, key=lambda m: np.nanmean([v for v in ms[m].values() if v is not None] or [np.nan])):
                v = np.array([x for x in ms[m].values() if x is not None], float)
                if len(v):
                    lines.append(f"| {ds} | {m} | {v.mean():.4g} +- {v.std(ddof=1) if len(v) > 1 else 0:.2g} [{len(v)}] |")
        lines.append("")
    res["real"] = real
    (HERE / "results.json").write_text(json.dumps(res, indent=1, default=str))
    (HERE / "logs" / "tables.md").write_text("\n".join(lines))
    print("\n".join(lines[:80]))


if __name__ == "__main__":
    analyse()
