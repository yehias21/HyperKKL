"""Mechanical analysis of the case studies (PREREG.md section 4): tables, paired CIs over seeds, Holm, average
log-ratio to the best and worst-case ratio across knowledge levels, robustness, bits rule, requirements.

    python analyze_cs.py            -> results.json, tables.md
"""
import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy import stats

sys.path.insert(0, str(Path(__file__).resolve().parent))
HERE = Path(__file__).resolve().parent.parent
RUNS = HERE / "runs"
LEVELS = ["exact", "mm10", "mm30", "partial", "realistic"]
TIERS = ["id", "shape_ood", "sequence_ood"]
CASES = {"A": "quad_planar", "B": "cstr_exo"}
HK = "hk_A3"
GB_UDE = ["greybox_ekf", "greybox_ukf", "greybox_ekf_oracle", "ude5k_ekf", "ude5k_ukf"]
ORDER = ["hk_A3", "hk_A4+D3", "hk_A0", "ekf", "ukf", "ekf_oracle", "greybox_ekf", "greybox_ukf", "greybox_ekf_oracle",
         "ude5k_ekf", "ude5k_ukf", "node5k_ekf", "node5k_ukf", "gru140", "nlox140", "climatology"]
COMPETITORS = [m for m in ORDER if not m.startswith("hk_") and m != "climatology"]
ROBUST = {"A": ["poor_init", "outliers", "gps_loss"], "B": ["poor_init", "outliers", "sensor_loss"]}
# requirement (PREREG.md section 2): per unmeasured state, settled RMSE in plant units; OOD tiers x 1.5
REQ = {"A": {2: 0.15, 3: 0.10, 4: 0.035}, "B": {0: 0.05}}
UNM = {"A": [2, 3, 4], "B": [0]}


def load():
    """{(case, level, seed): {method: {tier: {cond: block}}}} + meta {method: info} + x_std per case."""
    data, meta, xstd = {}, {}, {}
    for case in CASES:
        for level in LEVELS:
            for d in sorted((RUNS / case / level).glob("seed*")):
                seed = int(d.name[4:])
                for f in d.glob("*.json"):
                    p = json.loads(f.read_text())
                    xstd[case] = p["scales"]["x_std"]
                    for tier, cs in p["results"].items():
                        for cond, ms in cs.items():
                            for m, blk in ms.items():
                                data.setdefault((case, level, seed), {}).setdefault(m, {}).setdefault(tier, {})[cond] = blk
                    for m, info in p["methods"].items():
                        meta.setdefault((case, level, m), []).append(info)
    return data, meta, xstd


def per_seed(data, case, level, m, tier, cond="clean", key="nrmse_unmeasured"):
    """{seed: per-episode array}"""
    out = {}
    for (c, l, s), ms in data.items():
        if c == case and l == level and m in ms and tier in ms[m] and cond in ms[m][tier]:
            out[s] = np.asarray(ms[m][tier][cond][key], float)
    return out


def seed_means(data, case, level, m, tier, cond="clean", key="nrmse_unmeasured"):
    ps = per_seed(data, case, level, m, tier, cond, key)
    return {s: float(np.mean(v)) for s, v in ps.items()}


def tci(v, alpha=0.05):
    v = np.asarray(v, float)
    if len(v) < 2:
        return (float(v.mean()) if len(v) else float("nan"),) + (float("nan"),) * 2
    m, se = v.mean(), v.std(ddof=1) / math.sqrt(len(v))
    q = stats.t.ppf(1 - alpha / 2, len(v) - 1)
    return float(m), float(m - q * se), float(m + q * se)


def paired(data, case, level, a, b, tier, cond="clean", key="nrmse_unmeasured"):
    """r_s = (mean_a - mean_b) / mean_b per seed (same episodes); mean, t-CI, p (one-sample t vs 0)."""
    A, B = seed_means(data, case, level, a, tier, cond, key), seed_means(data, case, level, b, tier, cond, key)
    S = sorted(set(A) & set(B))
    if len(S) < 2:
        return None
    r = np.array([(A[s] - B[s]) / B[s] for s in S])
    m, lo, hi = tci(r)
    p = float(stats.ttest_1samp(r, 0.0).pvalue) if np.std(r) > 0 else (0.0 if m != 0 else 1.0)
    return {"r": m, "lo": lo, "hi": hi, "p": p, "n": len(S), "seeds": S}


def holm(ps):
    """Holm-adjusted p-values (same order)."""
    idx = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for k, i in enumerate(idx):
        run = max(run, min(1.0, (len(ps) - k) * ps[i]))
        adj[i] = run
    return adj


def best_of(data, case, level, tier, cands, cond="clean"):
    sm = {m: seed_means(data, case, level, m, tier, cond) for m in cands}
    sm = {m: np.mean(list(v.values())) for m, v in sm.items() if v}
    return min(sm, key=sm.get) if sm else None


def main():
    data, meta, xstd = load()
    out = {"cells": {}, "compare": {}, "minimax": {}, "robust": {}, "bits": {}, "requirements": {}, "meta": {}}
    md = ["# Case studies: mechanical tables (generated by code/analyze_cs.py)", ""]
    methods_present = sorted({m for ms in data.values() for m in ms}, key=lambda m: ORDER.index(m) if m in ORDER else 99)

    # 1. accuracy tables
    for case in CASES:
        for tier in TIERS:
            md += [f"## Case {case}, tier {tier}: settled NRMSE on unmeasured states (seed mean [95% t-CI], n seeds; div = divergence rate)", "",
                   "| method | " + " | ".join(LEVELS) + " |", "|---|" + "---|" * len(LEVELS)]
            for m in methods_present:
                row = [m]
                for level in LEVELS:
                    sm = seed_means(data, case, level, m, tier)
                    if not sm:
                        row.append("-"); continue
                    mu, lo, hi = tci(list(sm.values()))
                    dv = np.mean([np.mean(v) for v in per_seed(data, case, level, m, tier, key="diverged").values()])
                    out["cells"].setdefault(case, {}).setdefault(tier, {}).setdefault(level, {})[m] = \
                        {"mean": mu, "lo": lo, "hi": hi, "n": len(sm), "div": float(dv), "per_seed": sm}
                    row.append(f"{mu:.4f} [{lo:.4f}, {hi:.4f}] n{len(sm)}" + (f" div {dv:.2f}" if dv > 0 else ""))
                md.append("| " + " | ".join(row) + " |")
            md.append("")

    # 2. HyperKKL A3 vs every competitor and vs the best grey-box/UDE (oracle pick), Holm per (case, tier, comparator)
    for case in CASES:
        for tier in TIERS:
            md += [f"## Case {case}, tier {tier}: HyperKKL A3 vs comparators, paired relative difference (A3 - c) / c "
                   "[95% t-CI], Holm over the 5 levels; win/lose = Holm p < 0.05", "",
                   "| comparator | " + " | ".join(LEVELS) + " |", "|---|" + "---|" * len(LEVELS)]
            for comp in ["BEST_GB_UDE"] + [c for c in COMPETITORS if c in methods_present] + ["hk_A0"]:
                res = []
                for level in LEVELS:
                    c = best_of(data, case, level, tier, GB_UDE) if comp == "BEST_GB_UDE" else comp
                    r = paired(data, case, level, HK, c, tier) if c else None
                    res.append((level, c, r))
                ps = [r["p"] for _, _, r in res if r]
                adj = iter(holm(ps)) if ps else iter([])
                row = [comp]
                for level, c, r in res:
                    if r is None:
                        row.append("-"); continue
                    r["p_holm"] = next(adj)
                    r["verdict"] = ("win" if r["r"] < 0 else "lose") if r["p_holm"] < 0.05 else "tie"
                    r["comparator"] = c
                    out["compare"].setdefault(case, {}).setdefault(tier, {}).setdefault(comp, {})[level] = r
                    row.append(f"{100 * r['r']:+.0f}% [{100 * r['lo']:+.0f}, {100 * r['hi']:+.0f}] {r['verdict']}"
                               + (f" ({c})" if comp == "BEST_GB_UDE" else ""))
                md.append("| " + " | ".join(row) + " |")
            md.append("")

    # 3. knowledge-agnostic summary: average log-ratio to the best and worst-case ratio across levels
    for case in CASES:
        for tier in TIERS:
            cells = out["cells"].get(case, {}).get(tier, {})
            rows = {}
            for m in methods_present:
                lr, rs = [], []
                for level in LEVELS:
                    c = cells.get(level, {})
                    if m not in c:
                        continue
                    best = min(v["mean"] for k, v in c.items() if k != "climatology")
                    rs.append(c[m]["mean"] / best); lr.append(math.log(c[m]["mean"] / best))
                if len(rs) == len(LEVELS):
                    rows[m] = {"avg_log_ratio": float(np.mean(lr)), "geo_mean_ratio": float(np.exp(np.mean(lr))),
                               "worst_ratio": float(max(rs)), "worst_level": LEVELS[int(np.argmax(rs))],
                               "ratios": dict(zip(LEVELS, rs))}
            out["minimax"].setdefault(case, {})[tier] = rows
            md += [f"## Case {case}, tier {tier}: knowledge-agnostic ranking (ratio to the best method of each level)", "",
                   "| method | geo-mean ratio | worst-case ratio (level) | " + " | ".join(LEVELS) + " |",
                   "|---|---|---|" + "---|" * len(LEVELS)]
            for m, v in sorted(rows.items(), key=lambda kv: kv[1]["worst_ratio"]):
                md.append(f"| {m} | {v['geo_mean_ratio']:.2f} | {v['worst_ratio']:.2f} ({v['worst_level']}) | "
                          + " | ".join(f"{v['ratios'][l]:.2f}" for l in LEVELS) + " |")
            md.append("")

    # 4. robustness (id tier)
    for case in CASES:
        md += [f"## Case {case}: robustness (id tier; seed means; NRMSE unmeasured, divergence, convergence / recovery)", ""]
        for level in LEVELS:
            md += [f"### level {level}", "",
                   "| method | clean | " + " | ".join(ROBUST[case]) + " | poor_init t_conv median [s] | outage recovery median [s] | div (any cond) |",
                   "|---|---|" + "---|" * len(ROBUST[case]) + "---|---|---|"]
            for m in methods_present:
                cl = seed_means(data, case, level, m, "id")
                if not cl:
                    continue
                row = [m, f"{np.mean(list(cl.values())):.4f}"]
                divs = []
                rec = {}
                for cond in ROBUST[case]:
                    sm = seed_means(data, case, level, m, "id", cond)
                    dv = per_seed(data, case, level, m, "id", cond, "diverged")
                    divs += [float(np.mean(v)) for v in dv.values()]
                    row.append(f"{np.mean(list(sm.values())):.4f}" if sm else "-")
                    blks = [ms[m]["id"][cond]["scorecard"] for (c, l, s), ms in data.items()
                            if c == case and l == level and m in ms and cond in ms[m].get("id", {})]
                    rec[cond] = blks
                tc = [b.get("t_conv_median_s") for b in rec.get("poor_init", []) if b.get("t_conv_median_s") is not None]
                loss = ROBUST[case][2]
                rr = [b.get("rec_median_s") for b in rec.get(loss, []) if b.get("rec_median_s") is not None]
                nr = [b.get("rec_not_recovered") for b in rec.get(loss, []) if b.get("rec_not_recovered") is not None]
                row.append(f"{np.mean(tc):.2f}" if tc else "-")
                row.append((f"{np.mean(rr):.2f}" + (f" (not rec. {np.mean(nr):.2f})" if nr and np.mean(nr) > 0 else "")) if rr else "-")
                row.append(f"{max(divs):.3f}" if divs else "-")
                out["robust"].setdefault(case, {}).setdefault(level, {})[m] = {
                    "clean": float(np.mean(list(cl.values()))),
                    **{cond: float(np.mean(list(seed_means(data, case, level, m, "id", cond).values())))
                       for cond in ROBUST[case] if seed_means(data, case, level, m, "id", cond)},
                    "t_conv_poor_init_s": float(np.mean(tc)) if tc else None,
                    "recovery_s": float(np.mean(rr)) if rr else None,
                    "not_recovered": float(np.mean(nr)) if nr else None, "max_div": max(divs) if divs else None}
                md.append("| " + " | ".join(row) + " |")
            md.append("")

    # 5. bits rule
    bud = {}
    for case in CASES:
        p = HERE / "budgets" / f"{case}.json"
        if p.exists():
            bud[case] = json.loads(p.read_text())
    md += ["## Bits rule (held-out test): HyperKKL CANNOT beat a comparator with error eps if A > eps",
           "A = unmeasured Bayesian PCRB over the 3/alpha window (budgets/<case>.json); eps = best grey-box/UDE seed-mean "
           "unmeasured NRMSE (oracle pick); outcome = A3 vs that comparator (Holm). Violation = CANNOT predicted, win observed.", "",
           "| case | level | tier | A (3/alpha) | full-past bound | eps (comparator) | log2(A/eps) | prediction | A3 / eps | outcome | violation |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    tiermap = {"id": "eval_id", "sequence_ood": "eval_seq", "shape_ood": "eval_shape"}
    nviol, ncannot = 0, 0
    for case in bud:
        for level in LEVELS:
            for tier in TIERS:
                b = bud[case][level]["dists"].get(tiermap[tier])
                if b is None:
                    continue
                a = bud[case][level]["alpha"]
                A = b["bayes"]["windows"][f"{3 / a:g}"]["unmeasured_lb"]
                full = b["bayes"]["full"]["unmeasured_lb"]
                c = best_of(data, case, level, tier, GB_UDE)
                if not c:
                    continue
                eps = out["cells"][case][tier][level][c]["mean"]
                hk = out["cells"][case][tier][level].get(HK, {}).get("mean", float("nan"))
                pred = "CANNOT" if A > eps else "can"
                r = out["compare"].get(case, {}).get(tier, {}).get("BEST_GB_UDE", {}).get(level)
                outcome = r["verdict"] if r else "-"
                viol = pred == "CANNOT" and outcome == "win"
                nviol += viol; ncannot += pred == "CANNOT"
                out["bits"].setdefault(case, {}).setdefault(level, {})[tier] = {
                    "A": A, "full": full, "eps": eps, "comparator": c, "pred": pred, "hk": hk, "outcome": outcome,
                    "violation": viol}
                md.append(f"| {case} | {level} | {tier} | {A:.4f} | {full:.4f} | {eps:.4f} ({c}) | {math.log2(A / eps):+.2f} | "
                          f"{pred} | {hk / eps:.2f} | {outcome} | {'YES' if viol else 'no'} |")
    md += ["", f"CANNOT predictions: {ncannot}; violations: {nviol}.", ""]

    # 6. requirements (accuracy part; latency in latency tables)
    md += ["## Accuracy requirement (PREREG section 2): settled RMSE per unmeasured state in plant units, seed mean; "
           "OOD tiers allow 1.5x; plus no divergence in any condition", ""]
    for case in CASES:
        if case not in xstd:
            continue
        md += [f"### Case {case}", "", "| method | " + " | ".join(LEVELS) + " |", "|---|" + "---|" * len(LEVELS)]
        for m in methods_present:
            row = [m]
            for level in LEVELS:
                ok, worst = True, 0.0
                have = False
                for tier in TIERS:
                    for j, thr in REQ[case].items():
                        sm = seed_means(data, case, level, m, tier, key=f"nrmse_x{j + 1}")
                        if not sm:
                            continue
                        have = True
                        rmse = np.mean(list(sm.values())) * xstd[case][j]
                        lim = thr * (1.0 if tier == "id" else 1.5)
                        worst = max(worst, rmse / lim)
                        ok &= rmse <= lim
                rb = out["robust"].get(case, {}).get(level, {}).get(m, {})
                dv = out["cells"].get(case, {})
                anydiv = any(dv.get(t, {}).get(level, {}).get(m, {}).get("div", 0) > 0 for t in TIERS) or \
                    (rb.get("max_div") or 0) > 0
                if not have:
                    row.append("-"); continue
                passed = ok and not anydiv
                out["requirements"].setdefault(case, {}).setdefault(level, {})[m] = \
                    {"pass": bool(passed), "worst_frac_of_limit": float(worst), "diverged": bool(anydiv)}
                row.append(f"{'PASS' if passed else 'fail'} ({worst:.2f}x limit{', div' if anydiv else ''})")
            md.append("| " + " | ".join(row) + " |")
        md.append("")

    # meta: parameters, chosen lr
    for (case, level, m), infos in meta.items():
        npar = [i.get("n_params") for i in infos if isinstance(i, dict) and i.get("n_params") is not None]
        lrs = [i.get("lr") for i in infos if isinstance(i, dict) and i.get("lr") is not None]
        out["meta"].setdefault(case, {}).setdefault(level, {})[m] = {"n_params": npar[:1], "lrs": lrs}
    (HERE / "results.json").write_text(json.dumps(out, indent=1, default=str))
    (HERE / "tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
