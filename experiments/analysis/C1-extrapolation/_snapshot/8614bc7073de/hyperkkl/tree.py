"""The experiment tree: every experiment is a node, every node has one parent.

    experiments/tree/<id>/node.yaml          the node (human-editable)
    experiments/tree/<id>/report.md          generated by `report`
    experiments/tree/<id>/summary.json       generated by `report`
    experiments/tree/<id>/runs/<sys>/seed<k>/results.json, log.txt, error.txt
    experiments/TREE.md                      the whole tree, generated by `render`
    experiments/JOURNAL.md                   append-only log of node events

node.yaml fields
    id, parent, title             identity (root has parent: null)
    contribution                  C1 | C2 | C3 | C4 | infra
    question, hypothesis          what is tested and what we expect
    decision_rule                 how the verdict is decided, written BEFORE running
    set                           config overrides relative to the parent (dotted keys)
    methods, baselines            shorthand for set: {methods: ..., baselines: ...}
    systems, seeds                the job grid (inherited from the parent if absent)
    compare                       {tier, condition, reference}: what the report highlights
    status                        planned | queued | running | done | failed (maintained)
    verdict                       {outcome: supported|refuted|mixed|inconclusive, text, date}

A node's effective config = base.yaml + system yaml + the `set` of every ancestor from
the root down, then its own. Children therefore state only what they change.
"""

from __future__ import annotations

import datetime as _dt
import json
from pathlib import Path

import numpy as np
import yaml

from .config import ROOT, digest, get
from .metrics import hierarchical, paired_relative

EXP = ROOT / "experiments"
TREE = EXP / "tree"
QUEUE = EXP / "queue"
SHORTHAND = ("methods", "baselines")
EPISODE_KEYS = ("system", "data", "eval.n_episodes", "eval.split", "eval.rep")   # fix the eval episodes


# ---------------------------------------------------------------------------
# Node store
# ---------------------------------------------------------------------------

def node_path(nid: str) -> Path:
    return TREE / nid / "node.yaml"


def load_node(nid: str) -> dict:
    p = node_path(nid)
    if not p.exists():
        raise KeyError(f"no node {nid!r}")
    return yaml.safe_load(p.read_text())


def save_node(node: dict) -> None:
    p = node_path(node["id"])
    p.parent.mkdir(parents=True, exist_ok=True)
    order = ["id", "parent", "title", "contribution", "question", "hypothesis",
             "decision_rule", "set", "methods", "baselines", "systems", "seeds", "compare",
             "priority", "status", "created", "verdict", "notes"]
    out = {k: node[k] for k in order if k in node}
    out.update({k: v for k, v in node.items() if k not in out})
    p.write_text(yaml.safe_dump(out, sort_keys=False, width=92, allow_unicode=True))


def all_nodes() -> dict:
    return {p.parent.name: yaml.safe_load(p.read_text()) for p in sorted(TREE.glob("*/node.yaml"))}


def ancestors(nid: str) -> list:
    chain, cur = [], nid
    while cur:
        n = load_node(cur)
        chain.append(n)
        cur = n.get("parent")
    return chain[::-1]


def inherited(nid: str, key: str, default=None):
    for n in reversed(ancestors(nid)):
        if n.get(key) is not None:
            return n[key]
    return default


def resolved_overrides(nid: str) -> list:
    out = []
    for n in ancestors(nid):
        d = dict(n.get("set") or {})
        for k in SHORTHAND:
            if n.get(k) is not None:
                d[k] = n[k]
        out.append(d)
    return out


def jobs_of(nid: str) -> list:
    return [(s, int(k)) for s in inherited(nid, "systems", []) for k in inherited(nid, "seeds", [0])]


def run_dir(nid: str, system: str, seed: int) -> Path:
    return TREE / nid / "runs" / system / f"seed{seed}"


def journal(msg: str) -> None:
    EXP.mkdir(parents=True, exist_ok=True)
    with open(EXP / "JOURNAL.md", "a") as f:
        f.write(f"- {_dt.datetime.now():%Y-%m-%d %H:%M} — {msg}\n")


def new_node(nid, parent, title, **fields) -> dict:
    if node_path(nid).exists():
        raise FileExistsError(nid)
    if parent is not None:
        load_node(parent)
    node = {"id": nid, "parent": parent, "title": title, "status": "planned",
            "created": f"{_dt.date.today()}", **{k: v for k, v in fields.items() if v is not None}}
    save_node(node)
    journal(f"**{nid}** created under `{parent}`: {title}")
    return node


# ---------------------------------------------------------------------------
# Status
# ---------------------------------------------------------------------------

def progress(nid: str) -> dict:
    jobs = jobs_of(nid)
    done = sum((run_dir(nid, s, k) / "results.json").exists() for s, k in jobs)
    failed = sum((run_dir(nid, s, k) / "error.txt").exists() and
                 not (run_dir(nid, s, k) / "results.json").exists() for s, k in jobs)
    running = len(list((QUEUE / "running").glob(f"{nid}__*.json"))) if (QUEUE / "running").exists() else 0
    pending = len(list((QUEUE / "pending").glob(f"{nid}__*.json"))) if (QUEUE / "pending").exists() else 0
    return {"total": len(jobs), "done": done, "failed": failed, "running": running, "pending": pending}


def refresh_status(nid: str) -> str:
    n = load_node(nid)
    p = progress(nid)
    st = n.get("status", "planned")
    if p["running"]:                      # before done: a --force re-run is not finished
        st = "running"
    elif p["pending"]:
        st = "queued"
    elif p["total"] and p["done"] == p["total"]:
        st = "done"
    elif p["failed"]:
        st = "failed"
    if st != n.get("status"):
        n["status"] = st
        save_node(n)
        if st in ("done", "failed"):
            journal(f"**{nid}** {st} ({p['done']}/{p['total']} jobs)")
    return st


def queue(nid: str, force: bool = False) -> int:
    """Create a pending job for every (system, seed) without results. Idempotent: a job
    already pending or running is left alone (checked BEFORE results.json, so a job that
    finishes between the two checks is not queued twice)."""
    n = load_node(nid)
    (QUEUE / "pending").mkdir(parents=True, exist_ok=True)
    k = 0
    for s, seed in jobs_of(nid):
        rd = run_dir(nid, s, seed)
        name = f"{nid}__{s}__{seed}.json"
        if (QUEUE / "pending" / name).exists() or (QUEUE / "running" / name).exists():
            continue
        if (rd / "results.json").exists() and not force:
            continue
        (rd / "error.txt").unlink(missing_ok=True)
        (QUEUE / "failed" / name).unlink(missing_ok=True)
        (QUEUE / "pending" / name).write_text(json.dumps(
            {"node": nid, "system": s, "seed": seed, "priority": int(n.get("priority", 0)),
             "queued": f"{_dt.datetime.now():%Y-%m-%dT%H:%M:%S}"}))
        k += 1
    if k:
        n["status"] = "queued"
        save_node(n)
        journal(f"**{nid}** queued ({k} jobs)")
    return k


