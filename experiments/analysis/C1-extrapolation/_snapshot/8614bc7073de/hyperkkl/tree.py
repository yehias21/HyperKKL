def _load_runs(nid: str) -> dict:
    out = {}
    for s, k in jobs_of(nid):
        p = run_dir(nid, s, k) / "results.json"
        if p.exists():
            out.setdefault(s, {})[k] = json.loads(p.read_text())
    return out


def _refs(cmp_: dict) -> list:
    r = cmp_.get("reference")
    return [] if r is None else ([r] if isinstance(r, str) else list(r))


def summarize(nid: str, metric: str = "nrmse") -> dict:
    """{system: {tier: {condition: {method: {family|all: [mean, lo, hi, n_seeds]}}}}}
    plus paired comparisons {..: {reference: {method: {family|all: paired}}}}."""
    runs = _load_runs(nid)
    refs = _refs(inherited(nid, "compare", {}) or {})
    summary, paired, extra = {}, {}, {}
    for sysn, seeds in runs.items():
        any_r = next(iter(seeds.values()))
        extra[sysn] = {"params": {m: v.get("n_params") for m, v in any_r["train"].items()},
                       "cost_us_b1": {m: v.get("us_cpu_b1") for m, v in any_r.get("cost", {}).items()},
                       "wall_s": float(np.mean([r["wall_s"] for r in seeds.values()])),
                       "code": sorted({str(r.get("code")) for r in seeds.values()}),
                       "config": sorted({_config_digest(r.get("config") or {}) for r in seeds.values()}),
                       "phase1": {k: float(np.mean([r["phase1"]["diag"][k] for r in seeds.values()]))
                                  for k in any_r["phase1"]["diag"]}}
        for tier, conds in any_r["results"].items():
            for cname, res in conds.items():
                ufam = sorted(set(res["families"]))
                methods = list(res["methods"])

                def vals(m, fam):
                    out = []
                    for r in seeds.values():
                        rr = r["results"][tier][cname]
                        v = np.asarray(rr["methods"][m][metric], float)
                        f = np.asarray(rr["families"])
                        out.append(v if fam == "all" else v[f == fam])
                    return out

                for m in methods:
                    row = {fam: [*hierarchical(vals(m, fam), n_boot=1000), len(seeds)] for fam in ufam + ["all"]}
                    row["_diverged"] = float(np.mean([np.mean(r["results"][tier][cname]["methods"][m]["diverged"])
                                                      for r in seeds.values()]))
                    summary.setdefault(sysn, {}).setdefault(tier, {}).setdefault(cname, {})[m] = row
                for ref in refs:
                    if ref not in methods:
                        continue
                    for m in methods:
                        if m == ref:
                            continue
                        prow = {fam: paired_relative(vals(m, fam), vals(ref, fam), n_boot=1000)
                                for fam in ufam + ["all"]}
                        (paired.setdefault(sysn, {}).setdefault(tier, {}).setdefault(cname, {})
                         .setdefault(ref, {})[m]) = prow
    return {"metric": metric, "references": refs, "summary": summary, "paired": paired, "extra": extra}


def _config_digest(cfg: dict) -> str:
    """Digest of a run's config without its training seed (equal across a node's seeds)."""
    return digest(cfg, *sorted(k for k in cfg if k != "seed"))


def _fmt(v):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "–"
    return f"{v:.4f}" if abs(v) < 10 else f"{v:.2f}"


def _scoreboard(S, tier, cond) -> list:
    """Cross-system view: 'all'-column mean per method, and significant wins/losses."""
    L = []
    systems = [s for s in S["summary"] if cond in S["summary"][s].get(tier, {})]
    if not systems:
        return L
    methods = list(S["summary"][systems[0]][tier][cond])
    L += [f"## Scoreboard ({tier} / {cond}, all families)", "",
          "| method | " + " | ".join(systems) + " |", "|---" * (len(systems) + 1) + "|"]
    for m in methods:
        cells = []
        for s in systems:
            row = S["summary"][s][tier][cond].get(m)
            cells.append(_fmt(row["all"][0]) if row else "–")
        L.append(f"| {m} | " + " | ".join(cells) + " |")
    for ref in S["references"]:
        L += ["", f"Paired vs `{ref}` across systems (families where the 95% CI excludes 0: "
              f"better / worse; all-column change):", "",
              "| method | " + " | ".join(systems) + " |", "|---" * (len(systems) + 1) + "|"]
        for m in methods:
            if m == ref:
                continue
            cells = []
            for s in systems:
                pr = S["paired"].get(s, {}).get(tier, {}).get(cond, {}).get(ref, {}).get(m)
                if not pr:
                    cells.append("–"); continue
                fam = [f for f in pr if f != "all" and pr[f]]
                b = sum(pr[f]["better"] for f in fam); w = sum(pr[f]["worse"] for f in fam)
                al = pr.get("all") or {}
                rel = f"{100 * al['rel']:+.0f}%" if np.isfinite(al.get("rel", np.nan)) else "–"
                cells.append(f"{b}/{w} ({rel}{'*' if al.get('better') or al.get('worse') else ''})")
            L.append(f"| {m} | " + " | ".join(cells) + " |")
    L.append("")
    return L


def report(nid: str) -> Path:
    n = load_node(nid)
    cmp_ = inherited(nid, "compare", {}) or {}
    metrics = cmp_.get("metrics") or [cmp_.get("metric", "nrmse")]
    p = progress(nid)
    L = [f"# {nid} — {n.get('title', '')}", "",
         f"*parent* `{n.get('parent')}` · *contribution* {n.get('contribution', '–')} · "
         f"*status* {n.get('status')} · jobs {p['done']}/{p['total']}", ""]
    for k in ("question", "hypothesis", "decision_rule"):
        if n.get(k):
            L += [f"**{k.replace('_', ' ').capitalize()}.** {n[k]}", ""]
    if n.get("verdict"):
        v = n["verdict"]
        L += [f"**Verdict ({v.get('outcome')}, {v.get('date')}).** {v.get('text')}", ""]
    runs = _load_runs(nid)
    codes = sorted({str(r.get("code")) for seeds in runs.values() for r in seeds.values()})
    mixed = [s for s, seeds in runs.items()
             if len({_config_digest(r.get("config") or {}) for r in seeds.values()}) > 1]
    if len(codes) > 1 or mixed:
        L += [f"**WARNING: these runs come from {len(codes)} code versions ({', '.join(codes)})"
              + (f"; seeds of {', '.join(mixed)} ran with different configs" if mixed else "")
              + ". Re-run (queue --force) before drawing a verdict.**", ""]
    summaries = {}
    for metric in metrics:
        S = summarize(nid, metric)
        summaries[metric] = S
        L += [f"# Metric `{metric}`", "",
              "Definitions in hyperkkl/metrics.py. Mean over training seeds with a Student-t 95% "
              "CI over seeds (single-seed nodes: episode bootstrap, which ignores training "
              "variability); lower is better. Paired cells: mean per-seed relative change vs the "
              "reference, negative = better, bold = CI excludes 0. µs/step: CPU, batch 1.", ""]
        if len(inherited(nid, "seeds", [0])) < 2:
            L += ["> **Single seed**: intervals are episode-bootstrap only and do not support a "
                  "verdict about methods (training variability is not measured).", ""]
        L += _scoreboard(S, cmp_.get("tier", "ood"), cmp_.get("condition", "clean"))
        for sysn, tiers in S["summary"].items():
            L += [f"## {sysn}", ""]
            ex = S["extra"][sysn]
            L += ["phase 1: " + ", ".join(f"{k} {v:.3g}" for k, v in ex["phase1"].items())
                  + f" · mean job wall {ex['wall_s'] / 60:.1f} min", ""]
            for tier, conds in tiers.items():
                for cname, ms in conds.items():
                    fams = [f for f in next(iter(ms.values())) if not f.startswith("_")]
                    L += [f"### {tier} / {cname}", "",
                          "| method | " + " | ".join(fams) + " | div | params | µs/step |",
                          "|---" * (len(fams) + 4) + "|"]
                    best = {f: min((r[f][0] for r in ms.values() if np.isfinite(r[f][0])), default=np.nan)
                            for f in fams}
                    for m, row in ms.items():
                        cells = []
                        for f in fams:
                            mu, lo, hi, ns = row[f]
                            c = f"{_fmt(mu)} [{_fmt(lo)}, {_fmt(hi)}]"
                            cells.append(f"**{c}**" if np.isfinite(mu) and mu == best[f] else c)
                        L.append(f"| {m} | " + " | ".join(cells) + f" | {row['_diverged']:.2f} | "
                                 f"{ex['params'].get(m) or '–'} | {_fmt(ex['cost_us_b1'].get(m))} |")
                    for ref, pr in S["paired"].get(sysn, {}).get(tier, {}).get(cname, {}).items():
                        L += ["", f"Paired vs `{ref}`:", "",
                              "| method | " + " | ".join(fams) + " |", "|---" * (len(fams) + 1) + "|"]
                        for m, row in pr.items():
                            cells = []
                            for f in fams:
                                d = row.get(f) or {}
                                if not d or not np.isfinite(d["rel"]):
                                    cells.append("–"); continue
                                c = f"{100 * d['rel']:+.1f}% [{100 * d['ci'][0]:+.0f}, {100 * d['ci'][1]:+.0f}]"
                                cells.append(f"**{c}**" if d["better"] or d["worse"] else c)
                            L.append(f"| {m} | " + " | ".join(cells) + " |")
                    L.append("")
    (TREE / nid / "summary.json").write_text(json.dumps(summaries, indent=1, default=str))
    out = TREE / nid / "report.md"
    out.write_text("\n".join(L))
    return out


def headline(nid: str) -> str:
    """One line for TREE.md: the compare-condition 'all' column, best first."""
    sp = TREE / nid / "summary.json"
    if not sp.exists():
        return ""
    S = next(iter(json.loads(sp.read_text()).values()))
    cmp_ = inherited(nid, "compare", {}) or {}
    tier, cond = cmp_.get("tier", "ood"), cmp_.get("condition", "clean")
    parts = []
    for sysn, tiers in S["summary"].items():
        ms = tiers.get(tier, {}).get(cond, {})
        if not ms:
            continue
        ranked = sorted(ms.items(), key=lambda kv: (not np.isfinite(kv[1]["all"][0]), kv[1]["all"][0]))
        parts.append(f"{sysn}: " + " < ".join(f"{m} {kv['all'][0]:.3g}" for m, kv in ranked[:3]))
    return "; ".join(parts)


ICON = {"planned": "○", "queued": "◔", "running": "◑", "done": "●", "failed": "✗"}
OUTCOME = {"supported": "✔", "refuted": "✘", "mixed": "≈", "inconclusive": "?"}


def render() -> Path:
    nodes = all_nodes()
    kids = {}
    for nid, n in nodes.items():
        kids.setdefault(n.get("parent"), []).append(nid)
    L = ["# Experiment tree", "",
         "Generated by `python -m hyperkkl render`. Each node: status, id, title, progress, "
         "verdict. Open `tree/<id>/report.md` for tables, `tree/<id>/node.yaml` for the "
         "hypothesis and the config diff.", "",
         "Status: ○ planned · ◔ queued · ◑ running · ● done · ✗ failed. "
         "Verdict: ✔ supported · ✘ refuted · ≈ mixed · ? inconclusive.", "", "```"]

    def walk(nid, prefix, last):
        n = nodes[nid]
        p = progress(nid)
        v = n.get("verdict") or {}
        mark = OUTCOME.get(v.get("outcome"), "")
        conn = "" if prefix is None else (prefix + ("└── " if last else "├── "))
        L.append(f"{conn}{ICON.get(n.get('status'), '?')} {nid}  [{p['done']}/{p['total']}] "
                 f"{n.get('title', '')} {mark}".rstrip())
        ch = sorted(kids.get(nid, []), key=lambda c: (nodes[c].get("priority", 0), c))
        np_ = "" if prefix is None else prefix + ("    " if last else "│   ")
        for i, c in enumerate(ch):
            walk(c, np_, i == len(ch) - 1)

    for i, r in enumerate(sorted(kids.get(None, []))):
        walk(r, None, True)
    L += ["```", "", "## Nodes", ""]
    for nid, n in nodes.items():
        v = n.get("verdict") or {}
        L += [f"### {nid} — {n.get('title', '')}", "",
              f"- parent: `{n.get('parent')}` · contribution: {n.get('contribution', '–')} · "
              f"status: {n.get('status')}",
              f"- hypothesis: {n.get('hypothesis', '–')}",
              f"- decision rule: {n.get('decision_rule', '–')}"]
        hl = headline(nid)
        if hl:
            L.append(f"- headline ({(inherited(nid, 'compare', {}) or {}).get('tier', 'ood')}): {hl}")
        if v:
            L.append(f"- **verdict ({v.get('outcome')})**: {v.get('text')}")
        L.append("")
    out = EXP / "TREE.md"
    out.write_text("\n".join(L))
    return out


def set_verdict(nid: str, outcome: str, text: str) -> None:
    assert outcome in OUTCOME, outcome
    n = load_node(nid)
    n["verdict"] = {"outcome": outcome, "text": text, "date": f"{_dt.date.today()}"}
    save_node(n)
    journal(f"**{nid}** verdict {outcome}: {text}")


def cross_compare(a: str, b: str, tier="ood", cond="clean", metric="nrmse") -> dict:
    """Paired comparison of 'nodeA:method' against 'nodeB:method' on shared systems/seeds.

    Valid whenever both nodes evaluate the same episodes, i.e. their system, data and
    eval.n_episodes sections agree (evaluation seeds never depend on the node); this is
    checked on the configs stored with the runs (and the condition's definition), and a
    mismatch raises. ``same_code`` says whether both sides ran the same code version."""
    (na, ma), (nb, mb) = a.split(":", 1), b.split(":", 1)       # method names may hold ':'
    ra, rb = _load_runs(na), _load_runs(nb)
    out = {}
    for s in sorted(set(ra) & set(rb)):
        seeds = sorted(set(ra[s]) & set(rb[s]))
        av, bv = [], []
        for k in seeds:
            A_, B_ = ra[s][k]["results"][tier][cond], rb[s][k]["results"][tier][cond]
            if A_["families"] != B_["families"]:
                raise ValueError(f"{s} seed {k}: episodes differ between {na} and {nb}")
            ca, cb = ra[s][k].get("config") or {}, rb[s][k].get("config") or {}
            diff = [key for key in EPISODE_KEYS + (f"conditions.{cond}",) if get(ca, key) != get(cb, key)]
            if diff:
                raise ValueError(f"{s} seed {k}: {na} and {nb} evaluate different episodes ({', '.join(diff)} differ)")
            av.append(np.asarray(A_["methods"][ma][metric], float))
            bv.append(np.asarray(B_["methods"][mb][metric], float))
        out[s] = {"a": hierarchical(av, n_boot=1000)[0], "b": hierarchical(bv, n_boot=1000)[0],
                  "seeds": seeds, "same_code": all(ra[s][k].get("code") == rb[s][k].get("code") for k in seeds),
                  **paired_relative(av, bv, n_boot=1000)}
    return out
