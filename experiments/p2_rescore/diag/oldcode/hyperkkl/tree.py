def progress(nid: str) -> dict:
    jobs = jobs_of(nid)
    done = sum((run_dir(nid, s, k) / "results.json").exists() for s, k in jobs)
    failed = sum((run_dir(nid, s, k) / "error.txt").exists() and
                 not (run_dir(nid, s, k) / "results.json").exists() for s, k in jobs)
    running = len(list((QUEUE / "running").glob(f"{nid}__*.json"))) if (QUEUE / "running").exists() else 0
    pending = len(list((QUEUE / "pending").glob(f"{nid}__*.json"))) if (QUEUE / "pending").exists() else 0
    return {"total": len(jobs), "done": done, "failed": failed, "running": running, "pending": pending}


def refresh_status(nid: str) -> str:
    n = load_node(nid)
    p = progress(nid)
    st = n.get("status", "planned")
    if p["running"]:                      # before done: a --force re-run is not finished
        st = "running"
    elif p["pending"]:
        st = "queued"
    elif p["total"] and p["done"] == p["total"]:
        st = "done"
    elif p["failed"]:
        st = "failed"
    if st != n.get("status"):
        n["status"] = st
        save_node(n)
        if st in ("done", "failed"):
            journal(f"**{nid}** {st} ({p['done']}/{p['total']} jobs)")
    return st


def queue(nid: str, force: bool = False) -> int:
    """Create a pending job for every (system, seed) without results. Idempotent: a job
    already pending or running is left alone (checked BEFORE results.json, so a job that
    finishes between the two checks is not queued twice)."""
    n = load_node(nid)
    (QUEUE / "pending").mkdir(parents=True, exist_ok=True)
    k = 0
    for s, seed in jobs_of(nid):
        rd = run_dir(nid, s, seed)
        name = f"{nid}__{s}__{seed}.json"
        if (QUEUE / "pending" / name).exists() or (QUEUE / "running" / name).exists():
            continue
        if (rd / "results.json").exists() and not force:
            continue
        (rd / "error.txt").unlink(missing_ok=True)
        (QUEUE / "failed" / name).unlink(missing_ok=True)
        (QUEUE / "pending" / name).write_text(json.dumps(
            {"node": nid, "system": s, "seed": seed, "priority": int(n.get("priority", 0)),
             "queued": f"{_dt.datetime.now():%Y-%m-%dT%H:%M:%S}"}))
        k += 1
    if k:
        n["status"] = "queued"
        save_node(n)
        journal(f"**{nid}** queued ({k} jobs)")
    return k


