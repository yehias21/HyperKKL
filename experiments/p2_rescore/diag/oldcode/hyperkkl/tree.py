SC_TIERS = ("sequence_ood", "id", "shape_ood")      # preferred tier of a condition-specific column
# (key, header, kind): kind selects the cell format
SC_COLS = (("id", "id", "nrmse"), ("shape_ood", "shape_ood", "nrmse"),
           ("sequence_ood", "sequence_ood", "nrmse"),
           ("unmeasured", "unmeasured (seq)", "nrmse"),
           ("worst_sensor", "worst sensor fault", "nrmse"),
           ("p99", "p99 (seq)", "nrmse"), ("div", "div. rate (max)", "rate"),
           ("forget", "forget prior (poor_init)", "s"), ("conv", "conv. median (poor_init)", "s"), ("recovery", "recovery (burst)", "s"),
           ("drift", "drift (long)", "ratio"), ("auroc", "alarm AUROC (seq)", "auroc"),
           ("us", "µs/step", "us"))


def _fin_mean(v):
    v = [float(x) for x in v if x is not None and np.isfinite(float(x))]
    return float(np.mean(v)) if v else None


def _block(r: dict, tier, cond):
    return ((r.get("results") or {}).get(tier) or {}).get(cond)


def _sc_tier(seeds: dict, cond: str, pref=SC_TIERS):
    for t in list(pref) + sorted({t for r in seeds.values() for t in (r.get("results") or {})}):
        if any(_block(r, t, cond) for r in seeds.values()):
            return t
    return None


def _per_seed(seeds, tier, cond, fn):
    """Mean over seeds of fn(block) (None / non-finite values dropped)."""
    out = []
    for r in seeds.values():
        b = _block(r, tier, cond)
        if b:
            try:
                out.append(fn(b))
            except (KeyError, TypeError, ValueError):
                pass
    return _fin_mean(out)


def _ep_mean(m, key):
    return lambda b: float(np.mean(np.asarray(b["methods"][m][key], float)))


def _sc_get(m, key):
    return lambda b: b["scorecard"][m][key]


def scorecard_table(seeds: dict) -> dict:
    """{method: {col: (value, note)}} for one system of one node (seeds: {seed: payload}).
    Absent conditions / keys (older payloads) give no cell."""
    methods = []
    for r in seeds.values():
        for cs in (r.get("results") or {}).values():
            for b in cs.values():
                for m in (b.get("methods") or {}):
                    if m not in methods:
                        methods.append(m)
    any_r = next(iter(seeds.values()))
    conds_cfg = (any_r.get("config") or {}).get("conditions") or {}
    rows = {}
    for m in methods:
        row = {}
        for t in ("id", "shape_ood", "sequence_ood"):
            row[t] = (_per_seed(seeds, t, "clean", _ep_mean(m, "nrmse")), None)
        ts = _sc_tier(seeds, "clean")
        if ts:
            v = _per_seed(seeds, ts, "clean", _ep_mean(m, "nrmse_unmeasured"))
            row["unmeasured"] = (v, None if ts == "sequence_ood" else ts)
            row["p99"] = (_per_seed(seeds, ts, "clean",
                                    lambda b: float(np.percentile(np.asarray(b["methods"][m]["nrmse"], float), 99))),
                          None if ts == "sequence_ood" else ts)
            row["auroc"] = (_per_seed(seeds, ts, "clean", _sc_get(m, "alarm_auroc")),
                            None if ts == "sequence_ood" else ts)
        sens = [c for c, spec in conds_cfg.items() if isinstance(spec, dict) and spec.get("sensor")]
        worst = None
        for c in sens:
            tc = _sc_tier(seeds, c)
            v = _per_seed(seeds, tc, c, _ep_mean(m, "nrmse")) if tc else None
            if v is not None and (worst is None or v > worst[0]):
                worst = (v, c)
        row["worst_sensor"] = worst or (None, None)
        divs = []
        for t in {t for r in seeds.values() for t in (r.get("results") or {})}:
            for c in {c for r in seeds.values() for c in ((r.get("results") or {}).get(t) or {})}:
                v = _per_seed(seeds, t, c, _ep_mean(m, "diverged"))
                if v is not None:
                    divs.append((v, f"{t}/{c}"))
        row["div"] = max(divs) if divs else (None, None)
        for col, cond, key, note_key in (("forget", "poor_init", "t_forget_median_s", "forget_censored"),
                                         ("conv", "poor_init", "t_conv_median_s", "conv_censored"),
                                         ("recovery", "burst_outage", "rec_median_s", "rec_not_recovered"),
                                         ("drift", "long", "drift_ratio", None)):
            tc = _sc_tier(seeds, cond, ("id",) + SC_TIERS if cond == "long" else SC_TIERS)
            v = _per_seed(seeds, tc, cond, _sc_get(m, key)) if tc else None
            nv = _per_seed(seeds, tc, cond, _sc_get(m, note_key)) if (tc and note_key) else None
            row[col] = (v, f"{100 * nv:.0f}% cens." if nv else None)
        row["us"] = (_fin_mean([((r.get("cost") or {}).get(m) or {}).get("us_cpu_b1") for r in seeds.values()]), None)
        rows[m] = row
    return rows


def _sc_cell(v, note, kind):
    if v is None:
        return "–"
    txt = {"nrmse": _fmt(v), "rate": f"{v:.2f}", "s": f"{v:.3g} s", "ratio": f"{v:.3g}",
           "auroc": f"{v:.3f}", "us": f"{v:.3g}"}[kind]
    return f"{txt} ({note})" if note else txt


def _sc_columns(tables: dict) -> list:
    return [c for c in SC_COLS
            if any(row.get(c[0], (None,))[0] is not None for t in tables.values() for row in t.values())]


def scorecard_section(runs: dict) -> list:
    """Markdown lines: one scorecard table per system (rows = methods)."""
    tables = {s: scorecard_table(seeds) for s, seeds in runs.items() if seeds}
    if not tables:
        return []
    cols = _sc_columns(tables)
    L = ["## Deployment scorecard", "",
         "One row per method. nrmse columns: clean condition, mean over episodes and seeds; "
         "unmeasured = mean NRMSE over the unmeasured states; worst sensor fault = max over the "
         "sensor conditions present (named); p99 over episodes; div. rate = max over every "
         "tier/condition block (named); forget prior = median time until the poor_init estimate "
         "merges with the same observer's nominal-prior estimate (paired); conv. = median time "
         "after which the poor_init error stays below 2x its settled median; "
         "recovery = median time to return within 1.5x the pre-outage error after burst_outage; "
         "drift = NRMSE(last 20%) / NRMSE(20% after settling) on `long` episodes; alarm AUROC = "
         "output-residual alarm detecting state error > 3x median (metrics.py). Tier: "
         "sequence_ood unless named in the cell.", ""]
    for s, rows in tables.items():
        L += [f"### {s}", "", "| method | " + " | ".join(c[1] for c in cols) + " |",
              "|---" * (len(cols) + 1) + "|"]
        for m, row in rows.items():
            L.append(f"| {m} | " + " | ".join(_sc_cell(*row.get(k, (None, None)), kind) for k, _, kind in cols) + " |")
        L.append("")
    return L


def _tex(s: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("_", "\\_"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#"),
                 ("µ", "$\\mu$")):
        s = s.replace(a, b)
    return s


def scorecard(ids: list, out_dir: Path = None) -> tuple:
    """Cross-node scorecard: for every system, one row per (node, method). Writes
    <out_dir>/scorecard_<ids>.md and .tex (default experiments/scorecard/); returns both paths."""
    tables = {}
    for nid in ids:
        for s, seeds in _load_runs(nid).items():
            if not seeds:
                continue
            for m, row in scorecard_table(seeds).items():
                tables.setdefault(s, {})[f"{nid}:{m}" if len(ids) > 1 else m] = row
    cols = _sc_columns(tables)
    md = [f"# Deployment scorecard: {', '.join(ids)}", "",
          f"Generated by `python -m hyperkkl scorecard {' '.join(ids)}`. Columns as in the node "
          "reports (hyperkkl/tree.py, SC_COLS); tier sequence_ood unless named in the cell.", ""]
    tex = ["% generated by python -m hyperkkl scorecard " + " ".join(ids),
           "% requires \\usepackage{booktabs}"]
    for s, rows in tables.items():
        md += [f"## {s}", "", "| method | " + " | ".join(c[1] for c in cols) + " |",
               "|---" * (len(cols) + 1) + "|"]
        tex += ["\\begin{table}[t]", "\\centering", "\\scriptsize",
                f"\\caption{{Deployment scorecard, {_tex(s)}.}}",
                "\\begin{tabular}{l" + "r" * len(cols) + "}", "\\toprule",
                "method & " + " & ".join(_tex(c[1]) for c in cols) + " \\\\", "\\midrule"]
        for m, row in rows.items():
            cells = [_sc_cell(*row.get(k, (None, None)), kind) for k, _, kind in cols]
            md.append(f"| {m} | " + " | ".join(cells) + " |")
            tex.append(_tex(m) + " & " + " & ".join(_tex(c) for c in cells) + " \\\\")
        md.append("")
        tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    out_dir = Path(out_dir) if out_dir is not None else EXP / "scorecard"
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = "scorecard_" + "_".join(ids)
    if len(stem) > 120:
        import hashlib
        stem = stem[:100] + "_" + hashlib.sha1(stem.encode()).hexdigest()[:8]
    pm, pt = out_dir / f"{stem}.md", out_dir / f"{stem}.tex"
    pm.write_text("\n".join(md))
    pt.write_text("\n".join(tex))
    return pm, pt


def headline(nid: str, tier: str = None) -> str:
    """One line for TREE.md: the compare-condition 'all' column, best first."""
    sp = TREE / nid / "summary.json"
    if not sp.exists():
        return ""
    S = next(iter(json.loads(sp.read_text()).values()))
    cmp_ = inherited(nid, "compare", {}) or {}
    tier, cond = tier or cmp_.get("tier", DEFAULT_TIER), cmp_.get("condition", "clean")
    parts = []
    for sysn, tiers in S["summary"].items():
        ms = tiers.get(tier, {}).get(cond, {})
        if not ms:
            continue
        ranked = sorted(ms.items(), key=lambda kv: (not np.isfinite(kv[1]["all"][0]), kv[1]["all"][0]))
        parts.append(f"{sysn}: " + " < ".join(f"{m} {kv['all'][0]:.3g}" for m, kv in ranked[:3]))
    return "; ".join(parts)


ICON = {"planned": "○", "queued": "◔", "running": "◑", "done": "●", "failed": "✗"}
OUTCOME = {"supported": "✔", "refuted": "✘", "mixed": "≈", "inconclusive": "?"}


def render() -> Path:
    nodes = all_nodes()
    kids = {}
    for nid, n in nodes.items():
        kids.setdefault(n.get("parent"), []).append(nid)
    L = ["# Experiment tree", "",
         "Generated by `python -m hyperkkl render`. Each node: status, id, title, progress, "
         "verdict. Open `tree/<id>/report.md` for tables, `tree/<id>/node.yaml` for the "
         "hypothesis and the config diff.", "",
         "Status: ○ planned · ◔ queued · ◑ running · ● done · ✗ failed. "
         "Verdict: ✔ supported · ✘ refuted · ≈ mixed · ? inconclusive.", "", "```"]

    def walk(nid, prefix, last):
        n = nodes[nid]
        p = progress(nid)
        v = n.get("verdict") or {}
        mark = OUTCOME.get(v.get("outcome"), "")
        conn = "" if prefix is None else (prefix + ("└── " if last else "├── "))
        L.append(f"{conn}{ICON.get(n.get('status'), '?')} {nid}  [{p['done']}/{p['total']}] "
                 f"{n.get('title', '')} {mark}".rstrip())
        ch = sorted(kids.get(nid, []), key=lambda c: (nodes[c].get("priority", 0), c))
        np_ = "" if prefix is None else prefix + ("    " if last else "│   ")
        for i, c in enumerate(ch):
            walk(c, np_, i == len(ch) - 1)

    for i, r in enumerate(sorted(kids.get(None, []))):
        walk(r, None, True)
    L += ["```", "", "## Nodes", ""]
    for nid, n in nodes.items():
        v = n.get("verdict") or {}
        L += [f"### {nid} — {n.get('title', '')}", "",
              f"- parent: `{n.get('parent')}` · contribution: {n.get('contribution', '–')} · "
              f"status: {n.get('status')}",
              f"- hypothesis: {n.get('hypothesis', '–')}",
              f"- decision rule: {n.get('decision_rule', '–')}"]
        cmp_ = inherited(nid, "compare", {}) or {}
        for tier in ([cmp_["tier"]] if cmp_.get("tier") else list(PRIMARY_TIERS)):
            hl = headline(nid, tier)
            if hl:
                L.append(f"- headline ({tier}): {hl}")
        if v:
            L.append(f"- **verdict ({v.get('outcome')})**: {v.get('text')}")
        L.append("")
    out = EXP / "TREE.md"
    out.write_text("\n".join(L))
    return out


def set_verdict(nid: str, outcome: str, text: str) -> None:
    assert outcome in OUTCOME, outcome
