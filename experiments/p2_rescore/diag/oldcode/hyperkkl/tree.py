"""The experiment tree: every experiment is a node, every node has one parent.

    experiments/tree/<id>/node.yaml          the node (human-editable)
    experiments/tree/<id>/report.md          generated by `report`
    experiments/tree/<id>/summary.json       generated by `report`
    experiments/tree/<id>/runs/<sys>/seed<k>/results.json, log.txt, error.txt
    experiments/TREE.md                      the whole tree, generated by `render`
    experiments/JOURNAL.md                   append-only log of node events

node.yaml fields
    id, parent, title             identity (root has parent: null)
    contribution                  C1 | C2 | C3 | C4 | infra
    question, hypothesis          what is tested and what we expect
    decision_rule                 how the verdict is decided, written BEFORE running
    set                           config overrides relative to the parent (dotted keys)
    methods, baselines            shorthand for set: {methods: ..., baselines: ...}
    systems, seeds                the job grid (inherited from the parent if absent)
    compare                       {tier, condition, reference}: what the report highlights
                                  (tier optional: reports always show the shape_ood and
                                  sequence_ood scoreboards, then id)
    status                        planned | queued | running | done | failed (maintained)
    verdict                       {outcome: supported|refuted|mixed|inconclusive, text, date}

A node's effective config = base.yaml + system yaml + the `set` of every ancestor from
the root down, then its own. Children therefore state only what they change.
"""

