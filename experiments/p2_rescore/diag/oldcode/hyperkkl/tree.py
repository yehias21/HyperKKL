def report_tiers(cmp_: dict) -> list:
    """Tiers that get a scoreboard / headline: compare.tier (if set) first, then the
    primary OOD tiers and id. Tiers absent from the runs are skipped by the callers."""
    out = []
    for t in ([cmp_["tier"]] if cmp_.get("tier") else []) + list(PRIMARY_TIERS) + ["id"]:
        if t not in out:
            out.append(t)
    return out


