"""Add baselines to FINISHED runs without retraining (and without loading) the learned models.

    python -m hyperkkl reeval NODE [NODE ...] --baselines koopman_kf greybox_ekf ...
           [--systems vdp ...] [--seeds 0 1] [--device cuda:0] [--shard i/n] [--force]
           [--no-report] [--allow-code-drift] [--dry-run]

For every finished run (results.json) of each NODE: the run's own resolved config (stored
in results.json, including its per-seed pf / oracle tuning) rebuilds the job's training
data (data.training_data, cached) and evaluation blocks (evaluate._blocks via
data.eval_data, cached), the new baselines are fitted (baselines_data.fit_all for the data-
driven ones) and evaluated on exactly the original tiers x conditions, and their per-method
metrics, scorecard entries, train info, online cost and saved trajectories are MERGED into
the run (results.json, traj.npz). The first reeval keeps the original as results.json.bak;
every reeval appends a provenance record to payload['reeval'] (baselines, code hash and
snapshot of the reeval code, time, host, device, data-cache hits, wall times). The run's
own 'code' and 'config' are left as they were (they describe the original job).

Same episodes, guaranteed: the data modules (cache.DATA_MODULES) of the run's code snapshot
must hash to the current ones (else the cached data would be regenerated by other code;
--allow-code-drift overrides), the device type must match the run's (torch generators draw
differently on CPU and CUDA), the system scales must equal the stored ones, and every
block's episode families must equal the stored ones.
"""

from __future__ import annotations

import copy
import datetime as _dt
import fcntl
import hashlib
import json
import platform
import shutil
import tarfile
import time
from pathlib import Path

import numpy as np
import torch

from . import baselines_data as BD
from . import data as Dm
from . import tree as Tr
from .cache import DATA_MODULES, module_hash
from .config import ROOT


def snapshot_data_hash(code_snapshot: str) -> str | None:
    """module_hash(DATA_MODULES) of a run's code snapshot (None if the tarball is missing)."""
    p = ROOT / code_snapshot if code_snapshot else None
    if p is None or not p.exists():
        return None
    h = hashlib.sha1()
    with tarfile.open(p) as tf:
        for n in DATA_MODULES:
            h.update(tf.extractfile(f"hyperkkl/{n}.py").read())
    return h.hexdigest()[:10]


def finished_runs(nid: str, systems=None, seeds=None) -> list:
    out = []
    for s, k in Tr.jobs_of(nid):
        if (systems and s not in systems) or (seeds is not None and k not in seeds):
            continue
        p = Tr.run_dir(nid, s, k) / "results.json"
        if p.exists():
            out.append((s, k, p))
    return out


def _check_scales(stored: dict, now: dict) -> None:
    for k in ("x_std", "y_std", "dt", "N", "domain"):
        if k in stored and not np.allclose(np.asarray(stored[k], float), np.asarray(now[k], float),
                                           rtol=1e-6, atol=1e-12):
            raise RuntimeError(f"system scales differ from the run's ({k}): the episodes would not match")


def reeval_run(path: Path, baselines: list, device: str, log=print, force: bool = False,
               allow_code_drift: bool = False) -> dict:
    """Fit + evaluate ``baselines`` for the run at ``path`` (its results.json) and merge."""
    from . import job as J
    from .evaluate import build_observers, costs, evaluate
    path = Path(path)
    run_dir = path.parent
    lock = open(run_dir / "reeval.lock", "a")
    fcntl.flock(lock, fcntl.LOCK_EX)                  # one reeval per run at a time
    try:
        payload = json.loads(path.read_text())
        have = set()
        for cs in payload["results"].values():
            for b in cs.values():
                have |= set(b["methods"])
        todo = [b for b in baselines if force or b not in have]
        if not todo:
            log(f"  {run_dir}: {baselines} already present (use --force to recompute)")
            return {"skipped": True}
        cfg = copy.deepcopy(payload["config"])
        seed = int(payload["seed"])
        dev_run = torch.device(payload.get("device", "cpu")).type
        if torch.device(device).type != dev_run and not allow_code_drift:
            raise RuntimeError(f"run used device type {dev_run}, reeval asked for {device}: "
                               "the cached data are keyed by device type (pass a matching device)")
        h_snap = snapshot_data_hash(payload.get("code_snapshot"))
        h_now = module_hash(DATA_MODULES)
        if h_snap is not None and h_snap != h_now and not allow_code_drift:
            raise RuntimeError(f"data modules changed since the run (snapshot {h_snap}, now {h_now}): "
                               "the cached data would be regenerated by different code")
        if h_snap is None:
            log(f"  WARNING: no code snapshot for {run_dir}; data-module identity not verified")
        t0 = time.time()
        scales = Dm.system_scales(cfg, device)
        _check_scales(payload.get("scales") or {}, scales)
        des = Dm.make_design(cfg["system"])
        key_hit = _data_cached(cfg, seed, device)
        data = Dm.training_data(cfg, seed, device)
        t_data = time.time() - t0
        cfg_b = copy.deepcopy(cfg)
        cfg_b["baselines"] = list(todo)
        t0 = time.time()
        fits = BD.fit_all(cfg_b, data, scales, des, device, seed, log)
        t_fit = time.time() - t0
        obs = build_observers(cfg_b, des, scales, None, {}, None, device, fits)
        missing = [b for b in todo if b not in obs]
        if missing:
            raise ValueError(f"unknown or model-requiring baselines {missing} (reeval cannot build "
                             "learned-model observers such as kkl_mb or nlox)")
        timing = {}
        t0 = time.time()
        res = evaluate(cfg_b, des, scales, obs, device, log, timing=timing)
        t_eval = time.time() - t0
        traj = {}
        for tier, cs in res.items():
            for c, blk in cs.items():
                old = (payload["results"].get(tier) or {}).get(c)
                if old is None:
                    raise RuntimeError(f"block {tier}/{c} is not in the run")
                if list(old["families"]) != list(blk["families"]):
                    raise RuntimeError(f"block {tier}/{c}: episodes differ from the run's")
                for m in todo:
                    old["methods"][m] = blk["methods"][m]
                    old.setdefault("scorecard", {})[m] = blk["scorecard"][m]
                if "_traj" in blk:
                    traj.update({f"{tier}/{c}/{m}": v for m, v in blk["_traj"].items() if m in todo})
        nx, ny = len(scales["x_std"]), len(scales["y_std"])
        gpu = costs(obs, nx, ny, device)
        nt = torch.get_num_threads()
        torch.set_num_threads(1)
        try:
            cpu = costs(build_observers(cfg_b, des, scales, None, {}, None, "cpu", fits), nx, ny, "cpu")
        finally:
            torch.set_num_threads(nt)
        payload.setdefault("cost", {}).update(
            {m: {"us_gpu_b64": gpu[m].get("us_b64"), "us_cpu_b1": cpu[m].get("us_b1")} for m in todo})
        payload.setdefault("train", {}).update({m: fits["info"].get(m) for m in todo})
        payload.setdefault("eval_timing", {}).update({m: timing.get(m) for m in todo})
        ch = J.code_hash()
        rec = {"baselines": list(todo), "code": ch, "code_snapshot": J.snapshot_code(ch),
               "time": _dt.datetime.now().isoformat(timespec="seconds"), "host": platform.node(),
               "device": device, "data_modules": h_now, "data_cache_hit": key_hit,
               "data_s": t_data, "fit_s": t_fit, "eval_s": t_eval,
               "data_baselines": BD.options(cfg_b), "replaced": sorted(set(todo) & have)}
        payload.setdefault("reeval", []).append(rec)
        bak = run_dir / "results.json.bak"
        if not bak.exists():
            shutil.copy2(path, bak)
        if traj:
            tp = run_dir / "traj.npz"
            old = dict(np.load(tp)) if tp.exists() else {}
            old.update(traj)
            tmp = run_dir / "traj.tmp.npz"
            np.savez_compressed(tmp, **old)
            tmp.rename(tp)
        tmp = run_dir / "results.json.tmp"
        tmp.write_text(json.dumps(payload, default=J._json_default))
        tmp.rename(path)
        log(f"  merged {todo} into {path} (data {t_data:.0f}s, fit {t_fit:.0f}s, eval {t_eval:.0f}s)")
        return rec
    finally:
        fcntl.flock(lock, fcntl.LOCK_UN)
        lock.close()


def _data_cached(cfg, seed, device) -> bool:
    from .config import digest
    key = digest(cfg, "system", "data", extra=[seed, module_hash(DATA_MODULES), torch.device(device).type])
    return (Dm.CACHE / "data" / f"{cfg['system']['name']}_train_{key}.pt").exists()


def reeval_node(nid: str, baselines: list, device: str, systems=None, seeds=None, shard=(0, 1),
                force=False, allow_code_drift=False, report=True, dry_run=False, log=print) -> list:
    unknown = [b for b in baselines if b not in BD.DATA_BASELINES + ("ekf", "ukf", "ekf_huber", "ukf_huber",
                                                                     "pf", "ekf_oracle", "ukf_oracle",
                                                                     "ekf_oracle_huber")]
    if unknown:
        raise ValueError(f"reeval supports model-free-of-learned-maps baselines only; got {unknown}")
    runs = finished_runs(nid, systems, seeds)
    i, n = shard
    runs = [r for j, r in enumerate(runs) if j % n == i]
    out = []
    for s, k, p in runs:
        log(f"[{time.strftime('%H:%M:%S')}] reeval {nid} {s} seed{k}: {baselines}")
        if dry_run:
            out.append((s, k, None))
            continue
        out.append((s, k, reeval_run(p, baselines, device, log, force, allow_code_drift)))
    if report and not dry_run and out:
        Tr.report(nid)
    return out
