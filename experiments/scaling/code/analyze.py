"""Mechanical analysis (PREREG sections 5-8): results.json + tables.md.

    .venv/bin/python experiments/scaling/code/analyze.py
"""
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy import stats

SC = Path(__file__).resolve().parent.parent
NX = (4, 8, 16, 32, 64)
LEVELS = ("exact", "off30", "partial", "realistic")
TIERS = ("id", "shape_ood", "sequence_ood")
MF_LEVELS = {"D0": ("exact", "partial"), "D30": ("off30",), "DR": ("realistic",)}
METHODS = ("hkkl_A3", "hkkl_A0", "concat", "latent", "ekf", "ukf", "greybox_ekf", "greybox_ukf",
           "ude_ekf", "ude_ukf", "node_ekf", "gru", "nlox")
KKL = ("hkkl_A3", "hkkl_A0")


def load(sub=""):
    """R[(nx, level, method, tier)][seed] = dict(unm=array, all=array, div=array); M = method meta."""
    R, M, W = defaultdict(dict), defaultdict(dict), []
    for f in sorted((SC / "runs" / sub).glob("nx*/seed*/*.json")) if sub else sorted(SC.glob("runs/nx*/seed*/*.json")):
        if f.name.startswith("data_"):
            continue
        d = json.loads(f.read_text())
        kind, _, arg = d["unit"].partition(":")
        levels = MF_LEVELS[arg] if kind == "mf" else (arg,)
        W.append({"nx": d["nx"], "seed": d["seed"], "unit": d["unit"], "wall_h": d["wall_s"] / 3600,
                  "train_h": d["train_wall_s"] / 3600, "transitions": d["transitions"]})
        for lev in levels:
            for tier in TIERS:
                for m, v in d["results"][tier].items():
                    R[(d["nx"], lev, m, tier)][d["seed"]] = {k: np.asarray(v[x], float) for k, x in
                                                            (("unm", "nrmse_unmeasured"), ("all", "nrmse"),
                                                             ("div", "diverged"))}
            for m, mm in d["methods"].items():
                M[(d["nx"], lev, m)][d["seed"]] = mm
    return R, M, W


def smean(R, key, field="unm"):
    if key not in R:
        return None
    v = [R[key][s][field].mean() for s in sorted(R[key])]
    return float(np.mean(v)), (float(np.std(v, ddof=1)) if len(v) > 1 else 0.0), len(v)


def paired(R, a, b, field="unm"):
    """relative change a vs b, t-CI over common seeds."""
    if a not in R or b not in R:
        return None
    ss = sorted(set(R[a]) & set(R[b]))
    if len(ss) < 2:
        return None
    r = np.array([(R[a][s][field].mean() - R[b][s][field].mean()) / max(R[b][s][field].mean(), 1e-12) for s in ss])
    m, se = r.mean(), r.std(ddof=1) / math.sqrt(len(r))
    t = stats.t.ppf(0.975, len(r) - 1)
    p = float(2 * stats.t.sf(abs(m / max(se, 1e-300)), len(r) - 1))
    return {"rel": float(m), "lo": float(m - t * se), "hi": float(m + t * se), "p": p, "n": len(r)}


def holm(ps):
    order = np.argsort(ps); k = len(ps); out = [False] * k
    for i, j in enumerate(order):
        if ps[j] <= 0.05 / (k - i):
            out[j] = True
        else:
            break
    return out


def fmt(x):
    return "-" if x is None else f"{x[0]:.4f}"


def main():
    R, M, W = load()
    out = {"seed_means": {}, "best": {}, "P2": {}, "P3": {}, "P4": {}, "params": {}, "cost": {}}
    T = ["# Scaling study: all tables (generated by code/analyze.py)\n"]
    # ---- accuracy tables
    for tier in TIERS:
        for lev in LEVELS + ("avg", "worst"):
            T.append(f"\n## {tier} / {lev}: unmeasured-state NRMSE, seed mean (n seeds) vs n_x\n")
            T.append("| method | " + " | ".join(f"n_x={n}" for n in NX) + " |")
            T.append("|---|" + "---|" * len(NX))
            for m in METHODS:
                row = []
                for n in NX:
                    if lev in LEVELS:
                        s = smean(R, (n, lev, m, tier))
                    else:
                        v = [smean(R, (n, L_, m, tier)) for L_ in LEVELS]
                        s = None if any(x is None for x in v) else (
                            (float(np.mean([x[0] for x in v])) if lev == "avg" else float(max(x[0] for x in v))), 0, min(x[2] for x in v))
                    out["seed_means"][f"{tier}|{lev}|{m}|{n}"] = s
                    row.append("-" if s is None else f"{s[0]:.4f}" + (f" ±{s[1]:.4f}" if s[1] else "") + f" ({s[2]})")
                T.append(f"| {m} | " + " | ".join(row) + " |")
            for n in NX:
                c = [(out["seed_means"][f"{tier}|{lev}|{m}|{n}"][0], m) for m in METHODS
                     if out["seed_means"].get(f"{tier}|{lev}|{m}|{n}")]
                if c:
                    out["best"][f"{tier}|{lev}|{n}"] = min(c)[1]
            T.append("| **best** | " + " | ".join(out["best"].get(f"{tier}|{lev}|{n}", "-") for n in NX) + " |")
    # ---- divergence
    T.append("\n## Divergence rate (fraction of episodes, mean over seeds, all tiers and levels pooled)\n")
    T.append("| method | " + " | ".join(f"n_x={n}" for n in NX) + " |"); T.append("|---|" + "---|" * len(NX))
    out["divergence"] = {}
    for m in METHODS:
        row = []
        for n in NX:
            v = [R[(n, L_, m, t)][s]["div"].mean() for L_ in LEVELS for t in TIERS if (n, L_, m, t) in R
                 for s in R[(n, L_, m, t)]]
            out["divergence"][f"{m}|{n}"] = float(np.mean(v)) if v else None
            row.append(f"{np.mean(v):.3f}" if v else "-")
        T.append(f"| {m} | " + " | ".join(row) + " |")
    # ---- HyperKKL A3 vs the best non-KKL observer (paired)
    T.append("\n## hkkl_A3 vs the best non-HyperKKL observer of the cell (oracle pick by seed mean), sequence_ood, unmeasured: rel. change [95% CI]\n")
    T.append("| level | " + " | ".join(f"n_x={n}" for n in NX) + " |"); T.append("|---|" + "---|" * len(NX))
    out["A3_vs_best_other"] = {}
    for tier in TIERS:
        for lev in LEVELS:
            row = []
            for n in NX:
                c = [(smean(R, (n, lev, m, tier))[0], m) for m in METHODS if m not in KKL + ("concat", "latent")
                     and smean(R, (n, lev, m, tier))]
                if not c:
                    row.append("-"); continue
                b = min(c)[1]
                p = paired(R, (n, lev, "hkkl_A3", tier), (n, lev, b, tier))
                out["A3_vs_best_other"][f"{tier}|{lev}|{n}"] = {"other": b, **(p or {})}
                row.append("-" if p is None else f"{100 * p['rel']:+.0f}% [{100 * p['lo']:+.0f}, {100 * p['hi']:+.0f}] vs {b}")
            if tier == "sequence_ood":
                T.append(f"| {lev} | " + " | ".join(row) + " |")
    # ---- P2
    T.append("\n## P2: advantage of hkkl_A0 (and A3) over concat / latent vs n_x (mean over seeds and levels)\n")
    T.append("| tier | vs | base | " + " | ".join(f"n_x={n}" for n in NX) + " | Spearman rho | per-level rho |")
    T.append("|---|---|---|" + "---|" * len(NX) + "---|---|")
    checks = []
    for tier in ("shape_ood", "sequence_ood", "id"):
        for B in ("concat", "latent"):
            for A in ("hkkl_A0", "hkkl_A3"):
                adv, perlev = [], {}
                for n in NX:
                    v = []
                    for L_ in LEVELS:
                        a, b = R.get((n, L_, A, tier)), R.get((n, L_, B, tier))
                        if a and b:
                            ss = sorted(set(a) & set(b))
                            v.append(np.mean([(b[s]["unm"].mean() - a[s]["unm"].mean()) / b[s]["unm"].mean() for s in ss]))
                            perlev.setdefault(L_, []).append(v[-1])
                    adv.append(float(np.mean(v)) if len(v) == len(LEVELS) else None)
                ok = [i for i, x in enumerate(adv) if x is not None]
                rho = float(stats.spearmanr([NX[i] for i in ok], [adv[i] for i in ok])[0]) if len(ok) >= 3 else None
                pl = {L_: (round(float(stats.spearmanr(NX[:len(v)], v)[0]), 2) if len(v) >= 3 else None) for L_, v in perlev.items()}
                out["P2"][f"{tier}|{B}|{A}"] = {"adv": adv, "rho": rho, "n_points": len(ok), "per_level_rho": pl}
                if A == "hkkl_A0" and tier != "id":
                    checks.append(rho is not None and len(ok) == len(NX) and rho >= 0.8)
                T.append(f"| {tier} | {B} | {A} | " + " | ".join("-" if x is None else f"{100 * x:+.1f}%" for x in adv)
                         + f" | {'-' if rho is None else f'{rho:.2f}'} | {pl} |")
    out["P2"]["supported"] = bool(all(checks)) if len(checks) == 4 else None
    T.append(f"\nP2 verdict (4 checks, A0, shape and sequence OOD): {out['P2']['supported']}")
    # ---- P3
    guess = {"exact": "ukf", "off30": "ude_ukf", "partial": "ude_ukf", "realistic": "hkkl_A3"}
    T.append("\n## P3: most accurate at n_x = 64 (sequence_ood, unmeasured)\n")
    T.append("| level | guess | observed best | hit |"); T.append("|---|---|---|---|")
    for lev in LEVELS:
        b = out["best"].get(f"sequence_ood|{lev}|64")
        out["P3"][lev] = {"guess": guess[lev], "best": b, "hit": b == guess[lev]}
        T.append(f"| {lev} | {guess[lev]} | {b} | {b == guess[lev]} |")
    # ---- P4
    T.append("\n## P4: bits rule (A = window PCRB, unmeasured; eps = best grey-box / UDE unmeasured error)\n")
    T.append("| n_x | level | tier | A | eps (method) | rule | hkkl_A3 | outcome vs eps |"); T.append("|---|---|---|---|---|---|---|---|")
    ds = {"exact": "D0", "partial": "D0", "off30": "D30", "realistic": "DR"}
    n_forbid = 0; n_cells = 0
    for n in NX:
        f = SC / "inclusion" / f"ring{n}.json"
        if not f.exists():
            continue
        bud = json.loads(f.read_text())["budget"]
        for lev in LEVELS:
            for tier in ("id", "sequence_ood"):
                A = bud[ds[lev]]["A_window_unmeasured_lb"]
                c = [(smean(R, (n, lev, m, tier))[0], m) for m in ("greybox_ekf", "greybox_ukf", "ude_ekf", "ude_ukf")
                     if smean(R, (n, lev, m, tier))]
                k = smean(R, (n, lev, "hkkl_A3", tier))
                if not c or not k:
                    continue
                eps, gm = min(c)
                rule = "cannot win" if A > eps else "can win (silent)"
                n_cells += 1; n_forbid += A > eps
                outc = "win" if k[0] < eps else "lose"
                out["P4"][f"{n}|{lev}|{tier}"] = {"A": A, "eps": eps, "greybox": gm, "rule": rule, "A3": k[0], "outcome": outc}
                T.append(f"| {n} | {lev} | {tier} | {A:.4f} | {eps:.4f} ({gm}) | {rule} | {k[0]:.4f} | {outc} |")
    out["P4"]["forbidden_cells"] = [n_forbid, n_cells]
    # ---- params / data
    T.append("\n## Trainable parameters and training transitions per parameter (level partial / its dataset, seed 0)\n")
    T.append("| method | " + " | ".join(f"n_x={n}" for n in NX) + " |"); T.append("|---|" + "---|" * len(NX))
    for m in METHODS:
        row = []
        for n in NX:
            mm = M.get((n, "partial", m), {}).get(0)
            if mm:
                out["params"][f"{m}|{n}"] = {"params": mm["params_trainable"], "transitions": mm["train_transitions"]}
                row.append(f"{mm['params_trainable']:,} ({mm['transitions_per_param']:.1f})")
            else:
                row.append("-")
        T.append(f"| {m} | " + " | ".join(row) + " |")
    # ---- cost
    tot = sum(w["wall_h"] for w in W)
    T.append(f"\n## Training + evaluation cost: {tot:.1f} process-hours over {len(W)} units (shared GPUs)\n")
    T.append("| n_x | kkl units (h, mean) | gb units | mf units | transitions |"); T.append("|---|---|---|---|---|")
    for n in NX:
        g = lambda k: [w["wall_h"] for w in W if w["nx"] == n and w["unit"].startswith(k)]
        tr = [w["transitions"] for w in W if w["nx"] == n]
        out["cost"][n] = {k: (float(np.mean(g(k))) if g(k) else None) for k in ("kkl", "gb", "mf")}
        T.append(f"| {n} | " + " | ".join("-" if not g(k) else f"{np.mean(g(k)):.2f}" for k in ("kkl", "gb", "mf"))
                 + f" | {tr[0] if tr else '-'} |")
    out["cost"]["total_process_h"] = tot
    # ---- fixed data variant
    RF, MF_, WF = load("fixed4")
    if RF:
        T.append("\n## Fixed-data variant at n_x = 64 (n_x = 4 data amount) vs scaled data: unmeasured NRMSE, sequence_ood\n")
        T.append("| level | method | scaled data | fixed (small) data | rel. change [CI] |"); T.append("|---|---|---|---|---|")
        out["fixed_data"] = {}
        for lev in ("partial", "realistic"):
            for m in METHODS:
                a, b = smean(RF, (64, lev, m, "sequence_ood")), smean(R, (64, lev, m, "sequence_ood"))
                if a is None or b is None:
                    continue
                p = paired({**{("F",): RF.get((64, lev, m, "sequence_ood"))}, ("S",): R.get((64, lev, m, "sequence_ood"))},
                           ("F",), ("S",))
                out["fixed_data"][f"{lev}|{m}"] = {"scaled": b[0], "fixed": a[0], **(p or {})}
                T.append(f"| {lev} | {m} | {b[0]:.4f} | {a[0]:.4f} | " + ("-" if p is None else
                         f"{100 * p['rel']:+.0f}% [{100 * p['lo']:+.0f}, {100 * p['hi']:+.0f}]") + " |")
    # ---- latency
    out["latency"] = {}
    for dev in ("cpu", "cuda"):
        L = {}
        for f in sorted((SC / "latency").glob(f"nx*_{dev}.json")):
            d = json.loads(f.read_text())
            for m, v in d["methods"].items():
                if "us_median" in v:
                    L.setdefault(m, {})[d["nx"]] = (v["us_median"], v["flops"])
        if not L:
            continue
        nxs = sorted({n for v in L.values() for n in v})
        T.append(f"\n## Per-step latency at batch 1 on {dev} (us, median) [FLOPs/step] and scaling exponent b (cost ~ n_x^b, 95% CI)\n")
        T.append("| method | " + " | ".join(f"n_x={n}" for n in nxs) + " | b (latency) | b (FLOPs) |")
        T.append("|---|" + "---|" * len(nxs) + "---|---|")
        for m, v in sorted(L.items()):
            ns = sorted(v)
            def fit(y):
                x = np.log(ns); y = np.log(np.maximum(y, 1e-9))
                if len(ns) < 3:
                    return None
                r = stats.linregress(x, y); t = stats.t.ppf(0.975, len(ns) - 2)
                return [float(r.slope), float(r.slope - t * r.stderr), float(r.slope + t * r.stderr), float(r.stderr)]
            bl, bf = fit([v[n][0] for n in ns]), fit([max(v[n][1], 1) for n in ns])
            out["latency"][f"{dev}|{m}"] = {"us": {n: v[n][0] for n in ns}, "flops": {n: v[n][1] for n in ns},
                                           "b_latency": bl, "b_flops": bf}
            T.append(f"| {m} | " + " | ".join(f"{v[n][0]:.0f} [{v[n][1]:.2g}]" if n in v else "-" for n in nxs)
                     + f" | {'-' if not bl else f'{bl[0]:.2f} [{bl[1]:.2f}, {bl[2]:.2f}]'} | {'-' if not bf else f'{bf[0]:.2f}'} |")
        if dev == "cpu":         # P1
            res = []
            for F in ("ekf", "ukf", "ude_ekf", "ude_ukf"):
                for K in KKL:
                    a, b = out["latency"].get(f"cpu|{F}"), out["latency"].get(f"cpu|{K}")
                    if not a or not b or not a["b_latency"] or not b["b_latency"]:
                        continue
                    d = a["b_latency"][0] - b["b_latency"][0]
                    se = math.hypot(a["b_latency"][3], b["b_latency"][3])
                    df = 2 * (len(a["us"]) - 2)
                    res.append({"filter": F, "kkl": K, "diff": d, "p_one_sided": float(stats.t.sf(d / max(se, 1e-12), df))})
            hs = holm([r["p_one_sided"] for r in res]) if res else []
            for r, h in zip(res, hs):
                r["holm_sig"] = bool(h)
            out["P1"] = {"pairs": res, "supported": bool(res) and len(res) == 8 and all(hs)}
            T.append(f"\nP1 (CPU latency exponent filter > HyperKKL, Holm over pairs): {out['P1']}")
    (SC / "results.json").write_text(json.dumps(out, indent=1, default=str))
    (SC / "tables.md").write_text("\n".join(T) + "\n")
    print("\n".join(T[-60:]))


if __name__ == "__main__":
    main()
